//! Host-neutral assembly intent.
//!
//! Joints reference stable solid topology and store connector frames in model
//! space. This crate owns the host-neutral forward-kinematics solution but no
//! renderer or OCCT objects, so native, browser, CAM, and headless hosts all
//! consume the same persisted intent and solved body poses.

use std::collections::{HashMap, HashSet, VecDeque};

use nbcad_core::{BodyId, EdgeId, FaceId};
use nbcad_solid::{EdgeDto, FaceDto, SolidSceneDto};
use serde::{Deserialize, Serialize};
mod relations;
pub use relations::{CreateGearRelationRequestDto, GearRelationDto};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(transparent)]
pub struct JointId(pub u64);

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(transparent)]
pub struct ComponentId(pub u64);

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(transparent)]
pub struct OccurrenceId(pub u64);

/// Host-neutral rigid transform in translation plus x/y/z/w quaternion form.
/// Component coordinate systems and occurrence placements use the same value
/// type, but remain semantically separate in the persisted model.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
pub struct AssemblyTransformDto {
    pub translation: [f64; 3],
    pub rotation: [f64; 4],
}

impl Default for AssemblyTransformDto {
    fn default() -> Self {
        Self {
            translation: [0.0; 3],
            rotation: [0.0, 0.0, 0.0, 1.0],
        }
    }
}

/// Reusable definition of a part or subassembly component. Body ids point at
/// exact bodies generated by the solid feature history; no feature or OCCT
/// state is copied into the assembly model.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ComponentDefinitionDto {
    pub id: ComponentId,
    pub name: String,
    #[serde(default)]
    pub body_ids: Vec<BodyId>,
    /// Pose of the component-local coordinate system in part-model space.
    /// Occurrence transforms map this local system into their parent system.
    #[serde(default)]
    pub local_coordinate_system: AssemblyTransformDto,
    /// Automatically created compatibility definition for a live body that
    /// has not yet been organized by the user.
    #[serde(default)]
    pub promoted: bool,
}

/// One reusable instance of a component definition. Placements are authored
/// relative to the parent occurrence; a null parent is rooted in document
/// coordinates. Children form a nested subassembly tree.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ComponentOccurrenceDto {
    pub id: OccurrenceId,
    pub name: String,
    pub component_id: ComponentId,
    #[serde(default)]
    pub parent_occurrence_id: Option<OccurrenceId>,
    #[serde(default)]
    pub local_pose: AssemblyTransformDto,
    #[serde(default = "default_true")]
    pub visible: bool,
    #[serde(default)]
    pub grounded: bool,
}

/// Additive production component layer. Keeping it behind one defaulted field
/// lets every pre-component project deserialize and migrate deterministically.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ComponentStructureDto {
    #[serde(default)]
    pub definitions: Vec<ComponentDefinitionDto>,
    #[serde(default)]
    pub occurrences: Vec<ComponentOccurrenceDto>,
    #[serde(default = "default_next_component_id")]
    pub next_component_id: u64,
    #[serde(default = "default_next_occurrence_id")]
    pub next_occurrence_id: u64,
}

impl Default for ComponentStructureDto {
    fn default() -> Self {
        Self {
            definitions: Vec::new(),
            occurrences: Vec::new(),
            next_component_id: default_next_component_id(),
            next_occurrence_id: default_next_occurrence_id(),
        }
    }
}

impl ComponentStructureDto {
    pub fn validate(&self) -> Result<(), String> {
        let mut definition_ids = HashSet::new();
        let mut definition_names = HashSet::new();
        let mut body_owners = HashMap::<BodyId, ComponentId>::new();
        let mut max_definition_id = 0;
        for definition in &self.definitions {
            if definition.id.0 == 0 || !definition_ids.insert(definition.id) {
                return Err(format!(
                    "duplicate or zero component id {}",
                    definition.id.0
                ));
            }
            let name = definition.name.trim();
            if name.is_empty() || !definition_names.insert(name) {
                return Err(format!("duplicate or empty component name '{name}'"));
            }
            validate_transform(
                definition.local_coordinate_system,
                "component coordinate system",
            )?;
            let mut bodies = HashSet::new();
            for body_id in &definition.body_ids {
                if body_id.0 == 0 || !bodies.insert(*body_id) {
                    return Err(format!(
                        "component '{}' contains a duplicate or zero body id {}",
                        definition.name, body_id.0
                    ));
                }
                if let Some(owner) = body_owners.insert(*body_id, definition.id) {
                    return Err(format!(
                        "body {} belongs to both component {} and component {}",
                        body_id.0, owner.0, definition.id.0
                    ));
                }
            }
            max_definition_id = max_definition_id.max(definition.id.0);
        }
        if self.next_component_id == 0 || self.next_component_id <= max_definition_id {
            return Err(format!(
                "next component id {} must be greater than every saved component id",
                self.next_component_id
            ));
        }

        let mut occurrence_ids = HashSet::new();
        let mut sibling_names = HashSet::new();
        let mut grounded_parents = HashSet::new();
        let mut max_occurrence_id = 0;
        for occurrence in &self.occurrences {
            if occurrence.id.0 == 0 || !occurrence_ids.insert(occurrence.id) {
                return Err(format!(
                    "duplicate or zero occurrence id {}",
                    occurrence.id.0
                ));
            }
            if !definition_ids.contains(&occurrence.component_id) {
                return Err(format!(
                    "occurrence '{}' references missing component {}",
                    occurrence.name, occurrence.component_id.0
                ));
            }
            let name = occurrence.name.trim();
            if name.is_empty() || !sibling_names.insert((occurrence.parent_occurrence_id, name)) {
                return Err(format!(
                    "duplicate or empty occurrence name '{}' under the same parent",
                    name
                ));
            }
            if occurrence.parent_occurrence_id == Some(occurrence.id) {
                return Err(format!(
                    "occurrence {} cannot parent itself",
                    occurrence.id.0
                ));
            }
            validate_transform(occurrence.local_pose, "occurrence pose")?;
            if occurrence.grounded && !grounded_parents.insert(occurrence.parent_occurrence_id) {
                return Err(
                    "only one occurrence may be grounded within each subassembly".to_string(),
                );
            }
            max_occurrence_id = max_occurrence_id.max(occurrence.id.0);
        }
        if self.next_occurrence_id == 0 || self.next_occurrence_id <= max_occurrence_id {
            return Err(format!(
                "next occurrence id {} must be greater than every saved occurrence id",
                self.next_occurrence_id
            ));
        }
        for occurrence in &self.occurrences {
            if let Some(parent_id) = occurrence.parent_occurrence_id {
                if !occurrence_ids.contains(&parent_id) {
                    return Err(format!(
                        "occurrence '{}' references missing parent {}",
                        occurrence.name, parent_id.0
                    ));
                }
            }
            let mut visited = HashSet::new();
            let mut current = Some(occurrence.id);
            while let Some(id) = current {
                if !visited.insert(id) {
                    return Err(format!(
                        "occurrence hierarchy contains a cycle through {}",
                        id.0
                    ));
                }
                current = self
                    .occurrences
                    .iter()
                    .find(|candidate| candidate.id == id)
                    .and_then(|candidate| candidate.parent_occurrence_id);
            }
        }
        Ok(())
    }
}

impl AssemblyDocumentDto {
    /// Discard compatibility placeholders for consumed construction bodies.
    /// Call only after a successful replay at the end of the feature history;
    /// rollback scenes are incomplete and must retain their saved intent.
    pub fn remove_consumed_placeholders(
        &mut self,
        scene: &SolidSceneDto,
        referenced_bodies: &HashSet<BodyId>,
        referenced_occurrences: &HashSet<OccurrenceId>,
    ) -> Result<(), String> {
        if !scene.errors.is_empty() {
            return Ok(());
        }
        self.validate()?;
        let live = scene
            .bodies
            .iter()
            .map(|body| body.id)
            .collect::<HashSet<_>>();
        let mut discarded = HashSet::new();
        for definition in &self.component_structure.definitions {
            let [body] = definition.body_ids.as_slice() else {
                continue;
            };
            let default_name = format!("Body{}", body.0);
            if !definition.promoted
                || live.contains(body)
                || referenced_bodies.contains(body)
                || self.grounded_body_id == Some(*body)
                || definition.name != format!("{default_name} Part")
                || definition.local_coordinate_system != AssemblyTransformDto::default()
                || self.joints.iter().any(|joint| {
                    joint.connector_a.body_id == *body || joint.connector_b.body_id == *body
                })
                || self
                    .contact_sets
                    .iter()
                    .any(|contact| contact.body_a == *body || contact.body_b == *body)
            {
                continue;
            }
            let occurrences = self
                .component_structure
                .occurrences
                .iter()
                .filter(|occurrence| occurrence.component_id == definition.id)
                .collect::<Vec<_>>();
            if occurrences.len() > 1
                || occurrences.iter().any(|occurrence| {
                    occurrence.name != default_name
                        || occurrence.parent_occurrence_id.is_some()
                        || occurrence.local_pose != AssemblyTransformDto::default()
                        || !occurrence.visible
                        || occurrence.grounded
                        || referenced_occurrences.contains(&occurrence.id)
                        || self
                            .component_structure
                            .occurrences
                            .iter()
                            .any(|child| child.parent_occurrence_id == Some(occurrence.id))
                        || self.joints.iter().any(|joint| {
                            joint.advanced.connector_a_occurrence_id == Some(occurrence.id)
                                || joint.advanced.connector_b_occurrence_id == Some(occurrence.id)
                        })
                        || self.contact_sets.iter().any(|contact| {
                            contact.occurrence_a == occurrence.id
                                || contact.occurrence_b == occurrence.id
                        })
                })
            {
                continue;
            }
            discarded.insert(definition.id);
        }
        self.component_structure
            .occurrences
            .retain(|occurrence| !discarded.contains(&occurrence.component_id));
        self.component_structure
            .definitions
            .retain(|definition| !discarded.contains(&definition.id));
        // Keep monotonic allocation counters. A body reintroduced by an edit
        // receives a fresh default; no referenced identity was discarded.
        self.validate()
    }

    /// Promote every unorganized live body to a deterministic one-body
    /// component and root occurrence. This is the only legacy migration path;
    /// it never copies feature history or tessellation into assembly intent.
    pub fn synchronize_components(&mut self, scene: &SolidSceneDto) -> Result<(), String> {
        let mut bodies = scene.bodies.iter().collect::<Vec<_>>();
        bodies.sort_by_key(|body| body.id.0);
        for body in bodies {
            let already_defined = self
                .component_structure
                .definitions
                .iter()
                .any(|definition| definition.body_ids.contains(&body.id));
            if already_defined {
                continue;
            }
            let component_id = ComponentId(self.component_structure.next_component_id.max(1));
            self.component_structure.next_component_id = component_id
                .0
                .checked_add(1)
                .ok_or_else(|| "component id space is exhausted".to_string())?;
            let occurrence_id = OccurrenceId(self.component_structure.next_occurrence_id.max(1));
            self.component_structure.next_occurrence_id = occurrence_id
                .0
                .checked_add(1)
                .ok_or_else(|| "occurrence id space is exhausted".to_string())?;
            self.component_structure
                .definitions
                .push(ComponentDefinitionDto {
                    id: component_id,
                    name: format!("{} Part", body.name),
                    body_ids: vec![body.id],
                    local_coordinate_system: AssemblyTransformDto::default(),
                    promoted: true,
                });
            self.component_structure
                .occurrences
                .push(ComponentOccurrenceDto {
                    id: occurrence_id,
                    name: body.name.clone(),
                    component_id,
                    parent_occurrence_id: None,
                    local_pose: AssemblyTransformDto::default(),
                    visible: true,
                    grounded: self.grounded_body_id == Some(body.id),
                });
        }

        // A definition loaded without any occurrence remains reusable but not
        // visible. Promoted definitions always get their default root instance.
        let promoted_without_occurrences = self
            .component_structure
            .definitions
            .iter()
            .filter(|definition| {
                definition.promoted
                    && !self
                        .component_structure
                        .occurrences
                        .iter()
                        .any(|occurrence| occurrence.component_id == definition.id)
            })
            .cloned()
            .collect::<Vec<_>>();
        for definition in promoted_without_occurrences {
            let occurrence_id = OccurrenceId(self.component_structure.next_occurrence_id.max(1));
            self.component_structure.next_occurrence_id = occurrence_id
                .0
                .checked_add(1)
                .ok_or_else(|| "occurrence id space is exhausted".to_string())?;
            self.component_structure
                .occurrences
                .push(ComponentOccurrenceDto {
                    id: occurrence_id,
                    name: definition.name.trim_end_matches(" Part").to_string(),
                    component_id: definition.id,
                    parent_occurrence_id: None,
                    local_pose: AssemblyTransformDto::default(),
                    visible: true,
                    grounded: definition
                        .body_ids
                        .iter()
                        .any(|body_id| self.grounded_body_id == Some(*body_id)),
                });
        }

        for joint in &mut self.joints {
            if joint.advanced.connector_a_occurrence_id.is_none() {
                joint.advanced.connector_a_occurrence_id = self
                    .component_structure
                    .occurrence_for_body(joint.connector_a.body_id);
            }
            if joint.advanced.connector_b_occurrence_id.is_none() {
                joint.advanced.connector_b_occurrence_id = self
                    .component_structure
                    .occurrence_for_body(joint.connector_b.body_id);
            }
        }
        self.validate()
    }

    /// Build the non-destructive assembly view for the current feature-history
    /// marker. Undo can temporarily remove bodies while redo must retain their
    /// component/joint intent, so solving filters inactive references on a
    /// clone rather than deleting them from the project document.
    fn project_active_scene(&mut self, scene: &SolidSceneDto) -> Result<(), String> {
        self.synchronize_components(scene)?;
        let live_body_ids = scene
            .bodies
            .iter()
            .map(|body| body.id)
            .collect::<HashSet<_>>();

        for definition in &mut self.component_structure.definitions {
            definition
                .body_ids
                .retain(|body_id| live_body_ids.contains(body_id));
        }
        let definitions_with_bodies = self
            .component_structure
            .definitions
            .iter()
            .filter(|definition| !definition.body_ids.is_empty())
            .map(|definition| definition.id)
            .collect::<HashSet<_>>();
        let parents = self
            .component_structure
            .occurrences
            .iter()
            .map(|occurrence| (occurrence.id, occurrence.parent_occurrence_id))
            .collect::<HashMap<_, _>>();
        let mut active_occurrences = self
            .component_structure
            .occurrences
            .iter()
            .filter(|occurrence| definitions_with_bodies.contains(&occurrence.component_id))
            .map(|occurrence| occurrence.id)
            .collect::<HashSet<_>>();
        let mut frontier = active_occurrences.iter().copied().collect::<Vec<_>>();
        while let Some(occurrence_id) = frontier.pop() {
            if let Some(Some(parent)) = parents.get(&occurrence_id) {
                if active_occurrences.insert(*parent) {
                    frontier.push(*parent);
                }
            }
        }
        self.component_structure
            .occurrences
            .retain(|occurrence| active_occurrences.contains(&occurrence.id));

        self.joints.retain(|joint| {
            live_body_ids.contains(&joint.connector_a.body_id)
                && live_body_ids.contains(&joint.connector_b.body_id)
                && joint
                    .advanced
                    .connector_a_occurrence_id
                    .is_none_or(|id| active_occurrences.contains(&id))
                && joint
                    .advanced
                    .connector_b_occurrence_id
                    .is_none_or(|id| active_occurrences.contains(&id))
        });
        let active_joint_ids = self
            .joints
            .iter()
            .map(|joint| joint.id)
            .collect::<HashSet<_>>();
        self.gear_relations.retain(|relation| {
            active_joint_ids.contains(&relation.joint_a)
                && active_joint_ids.contains(&relation.joint_b)
        });
        for position in &mut self.positions {
            position
                .motions
                .retain(|motion| active_joint_ids.contains(&motion.joint_id));
        }
        for study in &mut self.motion_studies {
            study
                .drivers
                .retain(|driver| active_joint_ids.contains(&driver.joint_id));
        }
        self.contact_sets.retain(|contact| {
            live_body_ids.contains(&contact.body_a)
                && live_body_ids.contains(&contact.body_b)
                && active_occurrences.contains(&contact.occurrence_a)
                && active_occurrences.contains(&contact.occurrence_b)
        });
        if self
            .grounded_body_id
            .is_some_and(|body_id| !live_body_ids.contains(&body_id))
        {
            self.grounded_body_id = None;
        }
        self.validate()
    }

    pub fn create_component(
        &mut self,
        request: CreateComponentRequestDto,
        scene: &SolidSceneDto,
    ) -> Result<ComponentDefinitionDto, String> {
        self.synchronize_components(scene)?;
        let name = request.name.trim();
        if name.is_empty() {
            return Err("component name cannot be empty".to_string());
        }
        if self
            .component_structure
            .definitions
            .iter()
            .any(|definition| definition.name == name)
        {
            return Err(format!("duplicate component name '{name}'"));
        }
        validate_transform(
            request.local_coordinate_system,
            "component coordinate system",
        )?;
        let local_coordinate_system = normalized_transform(request.local_coordinate_system);
        let mut body_ids = request.body_ids;
        body_ids.sort_by_key(|body_id| body_id.0);
        body_ids.dedup();
        for body_id in &body_ids {
            if body_id.0 == 0 || !scene.bodies.iter().any(|body| body.id == *body_id) {
                return Err(format!("body {} does not exist", body_id.0));
            }
        }
        let overlapping = self
            .component_structure
            .definitions
            .iter()
            .filter(|definition| {
                definition
                    .body_ids
                    .iter()
                    .any(|body_id| body_ids.contains(body_id))
            })
            .collect::<Vec<_>>();
        if overlapping.iter().any(|definition| {
            !request.absorb_promoted_bodies
                || !definition.promoted
                || definition.body_ids.len() != 1
        }) {
            return Err(
                "one or more selected bodies already belong to an authored component".to_string(),
            );
        }

        let component_id = ComponentId(self.component_structure.next_component_id.max(1));
        let occurrence_id = OccurrenceId(self.component_structure.next_occurrence_id.max(1));
        self.component_structure.next_component_id = component_id
            .0
            .checked_add(1)
            .ok_or_else(|| "component id space is exhausted".to_string())?;
        self.component_structure.next_occurrence_id = occurrence_id
            .0
            .checked_add(1)
            .ok_or_else(|| "occurrence id space is exhausted".to_string())?;
        let definition = ComponentDefinitionDto {
            id: component_id,
            name: name.to_string(),
            body_ids: body_ids.clone(),
            local_coordinate_system,
            promoted: false,
        };
        let occurrence = ComponentOccurrenceDto {
            id: occurrence_id,
            name: name.to_string(),
            component_id,
            parent_occurrence_id: None,
            local_pose: local_coordinate_system,
            visible: true,
            grounded: false,
        };

        if request.absorb_promoted_bodies && !body_ids.is_empty() {
            let absorbed_definition_ids = self
                .component_structure
                .definitions
                .iter()
                .filter(|candidate| {
                    candidate.promoted
                        && candidate.body_ids.len() == 1
                        && body_ids.contains(&candidate.body_ids[0])
                })
                .map(|candidate| candidate.id)
                .collect::<HashSet<_>>();
            let absorbed_occurrence_ids = self
                .component_structure
                .occurrences
                .iter()
                .filter(|candidate| absorbed_definition_ids.contains(&candidate.component_id))
                .map(|candidate| candidate.id)
                .collect::<HashSet<_>>();
            for joint in &self.joints {
                let a_absorbed = joint
                    .advanced
                    .connector_a_occurrence_id
                    .is_some_and(|id| absorbed_occurrence_ids.contains(&id));
                let b_absorbed = joint
                    .advanced
                    .connector_b_occurrence_id
                    .is_some_and(|id| absorbed_occurrence_ids.contains(&id));
                if a_absorbed && b_absorbed {
                    return Err(format!(
                        "joint '{}' would become internal to the new rigid component; suppress or delete it first",
                        joint.name
                    ));
                }
            }
            for joint in &mut self.joints {
                if joint
                    .advanced
                    .connector_a_occurrence_id
                    .is_some_and(|id| absorbed_occurrence_ids.contains(&id))
                {
                    joint.advanced.connector_a_occurrence_id = Some(occurrence_id);
                }
                if joint
                    .advanced
                    .connector_b_occurrence_id
                    .is_some_and(|id| absorbed_occurrence_ids.contains(&id))
                {
                    joint.advanced.connector_b_occurrence_id = Some(occurrence_id);
                }
            }
            self.component_structure
                .occurrences
                .retain(|candidate| !absorbed_occurrence_ids.contains(&candidate.id));
            self.component_structure
                .definitions
                .retain(|candidate| !absorbed_definition_ids.contains(&candidate.id));
        }

        self.component_structure
            .definitions
            .push(definition.clone());
        self.component_structure.occurrences.push(occurrence);
        self.validate()?;
        Ok(definition)
    }

    pub fn update_component(
        &mut self,
        request: UpdateComponentRequestDto,
        scene: &SolidSceneDto,
    ) -> Result<ComponentDefinitionDto, String> {
        self.synchronize_components(scene)?;
        let index = self
            .component_structure
            .definitions
            .iter()
            .position(|definition| definition.id == request.component.id)
            .ok_or_else(|| format!("component {} does not exist", request.component.id.0))?;
        let previous = self.component_structure.definitions[index].clone();
        let patch = request.component;
        let name = patch.name.unwrap_or_else(|| previous.name.clone());
        if name.trim().is_empty() {
            return Err("component name cannot be empty".to_string());
        }
        if self.component_structure.definitions.iter().enumerate().any(
            |(candidate_index, definition)| candidate_index != index && definition.name == name,
        ) {
            return Err(format!("duplicate component name '{}'", name));
        }
        let body_ids_list = patch.body_ids.unwrap_or_else(|| previous.body_ids.clone());
        let local_coordinate_system = patch
            .local_coordinate_system
            .unwrap_or(previous.local_coordinate_system);
        validate_transform(local_coordinate_system, "component coordinate system")?;
        let body_ids = body_ids_list.iter().copied().collect::<HashSet<_>>();
        if body_ids.len() != body_ids_list.len() {
            return Err("component body ids must be unique".to_string());
        }
        for body_id in &body_ids {
            if !scene.bodies.iter().any(|body| body.id == *body_id) {
                return Err(format!("body {} does not exist", body_id.0));
            }
        }
        let occurrence_ids = self
            .component_structure
            .occurrences
            .iter()
            .filter(|occurrence| occurrence.component_id == previous.id)
            .map(|occurrence| occurrence.id)
            .collect::<HashSet<_>>();
        for joint in &self.joints {
            if joint
                .advanced
                .connector_a_occurrence_id
                .is_some_and(|id| occurrence_ids.contains(&id))
                && !body_ids.contains(&joint.connector_a.body_id)
            {
                return Err(format!(
                    "component edit would break joint '{}': connector A body removed",
                    joint.name
                ));
            }
            if joint
                .advanced
                .connector_b_occurrence_id
                .is_some_and(|id| occurrence_ids.contains(&id))
                && !body_ids.contains(&joint.connector_b.body_id)
            {
                return Err(format!(
                    "component edit would break joint '{}': connector B body removed",
                    joint.name
                ));
            }
        }
        let updated = ComponentDefinitionDto {
            id: previous.id,
            name,
            body_ids: body_ids_list,
            local_coordinate_system: normalized_transform(local_coordinate_system),
            promoted: patch.promoted.unwrap_or(previous.promoted),
        };
        self.component_structure.definitions[index] = updated.clone();
        if let Err(error) = self.validate() {
            self.component_structure.definitions[index] = previous;
            return Err(error);
        }
        Ok(updated)
    }

    pub fn create_occurrence(
        &mut self,
        request: CreateOccurrenceRequestDto,
    ) -> Result<ComponentOccurrenceDto, String> {
        if self
            .component_structure
            .definition(request.component_id)
            .is_none()
        {
            return Err(format!(
                "component {} does not exist",
                request.component_id.0
            ));
        }
        if request
            .parent_occurrence_id
            .is_some_and(|parent| self.component_structure.occurrence(parent).is_none())
        {
            return Err("parent occurrence does not exist".to_string());
        }
        validate_transform(request.local_pose, "occurrence pose")?;
        let base_name = if request.name.trim().is_empty() {
            self.component_structure
                .definition(request.component_id)
                .map(|definition| definition.name.as_str())
                .unwrap_or("Occurrence")
        } else {
            request.name.trim()
        };
        let name = self
            .component_structure
            .unique_occurrence_name(request.parent_occurrence_id, base_name);
        let id = OccurrenceId(self.component_structure.next_occurrence_id.max(1));
        self.component_structure.next_occurrence_id =
            id.0.checked_add(1)
                .ok_or_else(|| "occurrence id space is exhausted".to_string())?;
        let occurrence = ComponentOccurrenceDto {
            id,
            name,
            component_id: request.component_id,
            parent_occurrence_id: request.parent_occurrence_id,
            local_pose: normalized_transform(request.local_pose),
            visible: true,
            grounded: false,
        };
        self.component_structure
            .occurrences
            .push(occurrence.clone());
        self.validate()?;
        Ok(occurrence)
    }

    pub fn update_occurrence(
        &mut self,
        request: UpdateOccurrenceRequestDto,
    ) -> Result<ComponentOccurrenceDto, String> {
        let index = self
            .component_structure
            .occurrences
            .iter()
            .position(|occurrence| occurrence.id == request.occurrence.id)
            .ok_or_else(|| format!("occurrence {} does not exist", request.occurrence.id.0))?;
        let previous = self.component_structure.occurrences[index].clone();
        let patch = request.occurrence;
        let name = patch.name.unwrap_or_else(|| previous.name.clone());
        if name.trim().is_empty() {
            return Err("occurrence name cannot be empty".to_string());
        }
        let component_id = patch.component_id.unwrap_or(previous.component_id);
        if self.component_structure.definition(component_id).is_none() {
            return Err(format!("component {} does not exist", component_id.0));
        }
        let parent_occurrence_id = match patch.parent_occurrence_id {
            Some(parent) => parent,
            None => previous.parent_occurrence_id,
        };
        if parent_occurrence_id
            .is_some_and(|parent| self.component_structure.occurrence(parent).is_none())
        {
            return Err("parent occurrence does not exist".to_string());
        }
        let local_pose = patch.local_pose.unwrap_or(previous.local_pose);
        validate_transform(local_pose, "occurrence pose")?;
        let updated = ComponentOccurrenceDto {
            id: previous.id,
            name,
            component_id,
            parent_occurrence_id,
            local_pose: normalized_transform(local_pose),
            visible: patch.visible.unwrap_or(previous.visible),
            grounded: patch.grounded.unwrap_or(previous.grounded),
        };
        self.component_structure.occurrences[index] = updated.clone();
        if let Err(error) = self.validate() {
            self.component_structure.occurrences[index] = previous;
            return Err(error);
        }
        Ok(updated)
    }

    pub fn set_occurrence_grounded(
        &mut self,
        request: SetOccurrenceGroundedRequestDto,
    ) -> Result<(), String> {
        let occurrence_index = self
            .component_structure
            .occurrences
            .iter()
            .position(|occurrence| occurrence.id == request.occurrence_id)
            .ok_or_else(|| format!("occurrence {} does not exist", request.occurrence_id.0))?;
        let occurrence_id = self.component_structure.occurrences[occurrence_index].id;
        let parent_occurrence_id =
            self.component_structure.occurrences[occurrence_index].parent_occurrence_id;
        self.component_structure.occurrences[occurrence_index].grounded = request.grounded;
        if request.grounded {
            for sibling in &mut self.component_structure.occurrences {
                if sibling.id != occurrence_id
                    && sibling.parent_occurrence_id == parent_occurrence_id
                {
                    sibling.grounded = false;
                }
            }
        }
        // Keep the legacy body field deterministic for older hosts, but only
        // root grounding participates in that single-value compatibility
        // projection. Nested subassemblies each own an independent ground.
        self.grounded_body_id = self
            .component_structure
            .occurrences
            .iter()
            .filter(|occurrence| occurrence.parent_occurrence_id.is_none() && occurrence.grounded)
            .min_by_key(|occurrence| occurrence.id.0)
            .and_then(|occurrence| {
                self.component_structure
                    .definition(occurrence.component_id)
                    .and_then(|definition| definition.body_ids.first().copied())
            });
        self.validate()
    }

    pub fn set_occurrence_pose(
        &mut self,
        request: SetOccurrencePoseRequestDto,
    ) -> Result<(), String> {
        validate_transform(request.local_pose, "occurrence pose")?;
        let occurrence = self
            .component_structure
            .occurrences
            .iter_mut()
            .find(|occurrence| occurrence.id == request.occurrence_id)
            .ok_or_else(|| format!("occurrence {} does not exist", request.occurrence_id.0))?;
        occurrence.local_pose = normalized_transform(request.local_pose);
        self.validate()
    }

    pub fn duplicate_occurrence_subtree(
        &mut self,
        request: DuplicateOccurrenceRequestDto,
    ) -> Result<ComponentOccurrenceDto, String> {
        if let Some(local_pose) = request.local_pose {
            validate_transform(local_pose, "duplicate occurrence pose")?;
        }
        // Allocate ids and clone the complete subtree on a candidate document.
        // A late validation failure must not consume ids or append a partial
        // occurrence/joint graph to the live assembly.
        let mut candidate = self.clone();
        let root = candidate.duplicate_occurrence_subtree_in_place(request)?;
        candidate.validate()?;
        *self = candidate;
        Ok(root)
    }

    fn duplicate_occurrence_subtree_in_place(
        &mut self,
        request: DuplicateOccurrenceRequestDto,
    ) -> Result<ComponentOccurrenceDto, String> {
        let source = self
            .component_structure
            .occurrence(request.occurrence_id)
            .cloned()
            .ok_or_else(|| format!("occurrence {} does not exist", request.occurrence_id.0))?;
        if request
            .parent_occurrence_id
            .is_some_and(|parent| self.component_structure.occurrence(parent).is_none())
        {
            return Err("duplicate target parent does not exist".to_string());
        }
        let mut descendants = Vec::new();
        let mut queue = VecDeque::from([source.id]);
        while let Some(parent) = queue.pop_front() {
            let mut children = self
                .component_structure
                .occurrences
                .iter()
                .filter(|occurrence| occurrence.parent_occurrence_id == Some(parent))
                .cloned()
                .collect::<Vec<_>>();
            children.sort_by_key(|occurrence| occurrence.id.0);
            for child in children {
                queue.push_back(child.id);
                descendants.push(child);
            }
        }
        let mut source_nodes = Vec::with_capacity(descendants.len() + 1);
        source_nodes.push(source.clone());
        source_nodes.extend(descendants);
        let mut mapping = HashMap::<OccurrenceId, OccurrenceId>::new();
        let mut clones = Vec::new();
        for node in &source_nodes {
            let id = OccurrenceId(self.component_structure.next_occurrence_id.max(1));
            self.component_structure.next_occurrence_id =
                id.0.checked_add(1)
                    .ok_or_else(|| "occurrence id space is exhausted".to_string())?;
            mapping.insert(node.id, id);
            let parent_occurrence_id = if node.id == source.id {
                request.parent_occurrence_id
            } else {
                node.parent_occurrence_id
                    .and_then(|parent| mapping.get(&parent).copied())
            };
            clones.push(ComponentOccurrenceDto {
                id,
                name: self
                    .component_structure
                    .unique_occurrence_name(parent_occurrence_id, &node.name),
                component_id: node.component_id,
                parent_occurrence_id,
                local_pose: if node.id == source.id {
                    normalized_transform(request.local_pose.unwrap_or(node.local_pose))
                } else {
                    node.local_pose
                },
                visible: node.visible,
                grounded: false,
            });
        }
        let source_ids = mapping.keys().copied().collect::<HashSet<_>>();
        let mut cloned_joints = Vec::new();
        let mut joint_mapping = HashMap::new();
        for joint in &self.joints {
            let Some(a) = joint.advanced.connector_a_occurrence_id else {
                continue;
            };
            let Some(b) = joint.advanced.connector_b_occurrence_id else {
                continue;
            };
            if !source_ids.contains(&a) || !source_ids.contains(&b) {
                continue;
            }
            let mut clone = joint.clone();
            clone.id = JointId(self.next_joint_id.max(1));
            self.next_joint_id = clone
                .id
                .0
                .checked_add(1)
                .ok_or_else(|| "joint id space is exhausted".to_string())?;
            clone.name = unique_joint_name(&self.joints, &cloned_joints, &joint.name);
            clone.advanced.connector_a_occurrence_id = mapping.get(&a).copied();
            clone.advanced.connector_b_occurrence_id = mapping.get(&b).copied();
            joint_mapping.insert(joint.id, clone.id);
            cloned_joints.push(clone);
        }
        // Relations belong to the same occurrence subtree as their joints.
        // Repeated subassemblies retain independent coordinate coupling.
        let mut cloned_relations = Vec::new();
        for relation in &self.gear_relations {
            let (Some(a), Some(b)) = (
                joint_mapping.get(&relation.joint_a),
                joint_mapping.get(&relation.joint_b),
            ) else {
                continue;
            };
            let mut clone = relation.clone();
            clone.id = self.next_gear_relation_id;
            self.next_gear_relation_id = clone
                .id
                .checked_add(1)
                .ok_or("Gear relation IDs exhausted")?;
            clone.specification.joint_a = *a;
            clone.specification.joint_b = *b;
            clone.specification.name = format!("{}:{}", relation.name, clone.id);
            while self
                .gear_relations
                .iter()
                .chain(cloned_relations.iter())
                .any(|existing: &GearRelationDto| existing.name == clone.name)
            {
                clone.specification.name.push(':');
            }
            cloned_relations.push(clone);
        }
        self.gear_relations.extend(cloned_relations);
        let root = clones[0].clone();
        self.component_structure.occurrences.extend(clones);
        self.joints.extend(cloned_joints);
        Ok(root)
    }
}

impl ComponentStructureDto {
    fn definition(&self, id: ComponentId) -> Option<&ComponentDefinitionDto> {
        self.definitions
            .iter()
            .find(|definition| definition.id == id)
    }

    fn occurrence(&self, id: OccurrenceId) -> Option<&ComponentOccurrenceDto> {
        self.occurrences
            .iter()
            .find(|occurrence| occurrence.id == id)
    }

    fn occurrence_for_body(&self, body_id: BodyId) -> Option<OccurrenceId> {
        let definitions = self
            .definitions
            .iter()
            .map(|definition| (definition.id, definition))
            .collect::<HashMap<_, _>>();
        self.occurrences
            .iter()
            .filter(|occurrence| {
                definitions
                    .get(&occurrence.component_id)
                    .is_some_and(|definition| definition.body_ids.contains(&body_id))
            })
            .min_by_key(|occurrence| occurrence.id.0)
            .map(|occurrence| occurrence.id)
    }

    fn occurrence_contains_body(&self, occurrence_id: OccurrenceId, body_id: BodyId) -> bool {
        self.occurrence(occurrence_id)
            .and_then(|occurrence| self.definition(occurrence.component_id))
            .is_some_and(|definition| definition.body_ids.contains(&body_id))
    }

    fn unique_occurrence_name(&self, parent: Option<OccurrenceId>, base: &str) -> String {
        if !self
            .occurrences
            .iter()
            .any(|occurrence| occurrence.parent_occurrence_id == parent && occurrence.name == base)
        {
            return base.to_string();
        }
        for suffix in 2..u32::MAX {
            let candidate = format!("{base}:{suffix}");
            if !self.occurrences.iter().any(|occurrence| {
                occurrence.parent_occurrence_id == parent && occurrence.name == candidate
            }) {
                return candidate;
            }
        }
        format!("{base}:instance")
    }
}

