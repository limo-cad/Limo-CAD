fn unique_intent_name<T, F>(requested: &str, items: &[T], name_of: F) -> Result<String, String>
where
    F: Fn(&T) -> &str,
{
    let name = requested.trim();
    if name.is_empty() {
        return Err("name must not be empty".to_string());
    }
    if items.iter().any(|item| name_of(item) == name) {
        return Err(format!("duplicate name '{name}'"));
    }
    Ok(name.to_string())
}

fn validate_positive_finite(value: f64, label: &str) -> Result<(), String> {
    if !value.is_finite() || value <= 0.0 {
        return Err(format!("{label} must be positive and finite"));
    }
    Ok(())
}

fn canonical_motion_set(
    document: &AssemblyDocumentDto,
    motions: &[JointMotionStateDto],
) -> Result<Vec<JointMotionStateDto>, String> {
    let mut candidate = document.clone();
    candidate.apply_joint_motions(motions)?;
    let requested = motions
        .iter()
        .map(|motion| motion.joint_id)
        .collect::<HashSet<_>>();
    let mut result = candidate
        .current_joint_motions()
        .into_iter()
        .filter(|motion| requested.contains(&motion.joint_id))
        .collect::<Vec<_>>();
    result.sort_by_key(|motion| motion.joint_id.0);
    Ok(result)
}

fn validate_motion_study(
    study: &MotionStudyDto,
    joints: &[JointDefinitionDto],
) -> Result<(), String> {
    validate_positive_finite(study.duration_seconds, "motion study duration")?;
    validate_positive_finite(study.playback_speed, "motion study playback speed")?;
    if study.name.trim().is_empty() {
        return Err("motion study name must not be empty".to_string());
    }
    let mut ids = HashSet::new();
    let mut names = HashSet::new();
    let mut coordinates = HashSet::new();
    let mut max_id = 0;
    for driver in &study.drivers {
        if driver.id.0 == 0 || !ids.insert(driver.id) {
            return Err(format!(
                "motion study '{}' has a duplicate or zero driver id",
                study.name
            ));
        }
        if driver.name.trim().is_empty() || !names.insert(driver.name.trim()) {
            return Err(format!(
                "motion study '{}' has duplicate or empty driver names",
                study.name
            ));
        }
        if !coordinates.insert((driver.joint_id, driver.coordinate)) {
            return Err(format!(
                "motion study '{}' drives one joint coordinate more than once",
                study.name
            ));
        }
        let joint = joints
            .iter()
            .find(|joint| joint.id == driver.joint_id)
            .ok_or_else(|| {
                format!(
                    "driver '{}' references missing joint {}",
                    driver.name, driver.joint_id.0
                )
            })?;
        if !active_coordinates(joint.kind).contains(&driver.coordinate.to_internal()) {
            return Err(format!(
                "driver '{}' targets a coordinate unavailable on joint '{}'",
                driver.name, joint.name
            ));
        }
        match &driver.law {
            MotionDriverLawDto::Motor {
                initial_value,
                velocity_per_second,
                acceleration_per_second2,
            } => {
                if [
                    *initial_value,
                    *velocity_per_second,
                    *acceleration_per_second2,
                ]
                .iter()
                .any(|value| !value.is_finite())
                {
                    return Err(format!(
                        "motor driver '{}' contains a non-finite value",
                        driver.name
                    ));
                }
            }
            MotionDriverLawDto::Keyframes { keyframes } => {
                if keyframes.is_empty() {
                    return Err(format!(
                        "keyframe driver '{}' needs at least one keyframe",
                        driver.name
                    ));
                }
                let mut previous = f64::NEG_INFINITY;
                for keyframe in keyframes {
                    if !keyframe.time_seconds.is_finite()
                        || !keyframe.value.is_finite()
                        || keyframe.time_seconds < 0.0
                        || keyframe.time_seconds > study.duration_seconds
                        || keyframe.time_seconds <= previous
                    {
                        return Err(format!("keyframes for '{}' must be finite, strictly ordered, and inside the study duration", driver.name));
                    }
                    previous = keyframe.time_seconds;
                }
            }
        }
        max_id = max_id.max(driver.id.0);
    }
    if study.next_driver_id == 0 || study.next_driver_id <= max_id {
        return Err(format!(
            "motion study '{}' next driver id is invalid",
            study.name
        ));
    }
    Ok(())
}

fn validate_contact_set(
    contact: &ContactSetDto,
    structure: &ComponentStructureDto,
) -> Result<(), String> {
    if contact.name.trim().is_empty() {
        return Err("contact set name must not be empty".to_string());
    }
    if !contact.clearance_mm.is_finite() || contact.clearance_mm < 0.0 {
        return Err("contact clearance must be finite and non-negative".to_string());
    }
    if contact.occurrence_a == contact.occurrence_b && contact.body_a == contact.body_b {
        return Err("a contact set must reference two different placed bodies".to_string());
    }
    if !structure.occurrence_contains_body(contact.occurrence_a, contact.body_a)
        || !structure.occurrence_contains_body(contact.occurrence_b, contact.body_b)
    {
        return Err("contact set references a body outside its occurrence".to_string());
    }
    Ok(())
}

fn validate_motion_intent(document: &AssemblyDocumentDto) -> Result<(), String> {
    let mut position_ids = HashSet::new();
    let mut position_names = HashSet::new();
    let mut max_position_id = 0;
    for position in &document.positions {
        if position.id.0 == 0
            || !position_ids.insert(position.id)
            || position.name.trim().is_empty()
            || !position_names.insert(position.name.trim())
        {
            return Err(
                "saved positions must have unique non-zero ids and unique names".to_string(),
            );
        }
        canonical_motion_set(document, &position.motions)?;
        max_position_id = max_position_id.max(position.id.0);
    }
    if document.next_position_id == 0 || document.next_position_id <= max_position_id {
        return Err("next saved position id is invalid".to_string());
    }

    let mut study_ids = HashSet::new();
    let mut study_names = HashSet::new();
    let mut max_study_id = 0;
    for study in &document.motion_studies {
        if study.id.0 == 0
            || !study_ids.insert(study.id)
            || study.name.trim().is_empty()
            || !study_names.insert(study.name.trim())
        {
            return Err(
                "motion studies must have unique non-zero ids and unique names".to_string(),
            );
        }
        validate_motion_study(study, &document.joints)?;
        max_study_id = max_study_id.max(study.id.0);
    }
    if document.next_motion_study_id == 0 || document.next_motion_study_id <= max_study_id {
        return Err("next motion study id is invalid".to_string());
    }

    let mut contact_ids = HashSet::new();
    let mut contact_names = HashSet::new();
    let mut max_contact_id = 0;
    for contact in &document.contact_sets {
        if contact.id.0 == 0
            || !contact_ids.insert(contact.id)
            || contact.name.trim().is_empty()
            || !contact_names.insert(contact.name.trim())
        {
            return Err("contact sets must have unique non-zero ids and unique names".to_string());
        }
        validate_contact_set(contact, &document.component_structure)?;
        max_contact_id = max_contact_id.max(contact.id.0);
    }
    if document.next_contact_set_id == 0 || document.next_contact_set_id <= max_contact_id {
        return Err("next contact set id is invalid".to_string());
    }
    Ok(())
}

fn normalized_study_time(study: &MotionStudyDto, requested: f64) -> f64 {
    if study.looped && requested > study.duration_seconds {
        requested.max(0.0).rem_euclid(study.duration_seconds)
    } else {
        requested.clamp(0.0, study.duration_seconds)
    }
}

fn sample_driver(
    driver: &MotionDriverDto,
    time_seconds: f64,
    duration_seconds: f64,
) -> Result<MotionDriverSampleDto, String> {
    let (value, velocity_per_second, acceleration_per_second2) = match &driver.law {
        MotionDriverLawDto::Motor {
            initial_value,
            velocity_per_second,
            acceleration_per_second2,
        } => (
            initial_value
                + velocity_per_second * time_seconds
                + 0.5 * acceleration_per_second2 * time_seconds * time_seconds,
            velocity_per_second + acceleration_per_second2 * time_seconds,
            *acceleration_per_second2,
        ),
        MotionDriverLawDto::Keyframes { keyframes } => {
            if keyframes.is_empty() {
                return Err(format!("driver '{}' has no keyframes", driver.name));
            }
            if time_seconds <= keyframes[0].time_seconds {
                (keyframes[0].value, 0.0, 0.0)
            } else if time_seconds >= keyframes.last().expect("non-empty").time_seconds {
                (keyframes.last().expect("non-empty").value, 0.0, 0.0)
            } else {
                let pair = keyframes
                    .windows(2)
                    .find(|pair| {
                        time_seconds >= pair[0].time_seconds && time_seconds <= pair[1].time_seconds
                    })
                    .ok_or_else(|| {
                        format!("driver '{}' has an invalid keyframe range", driver.name)
                    })?;
                let left = pair[0];
                let right = pair[1];
                let span = right.time_seconds - left.time_seconds;
                let u = ((time_seconds - left.time_seconds) / span).clamp(0.0, 1.0);
                let delta = right.value - left.value;
                match left.interpolation {
                    MotionInterpolationDto::Step => (left.value, 0.0, 0.0),
                    MotionInterpolationDto::Linear => (left.value + delta * u, delta / span, 0.0),
                    MotionInterpolationDto::Smooth => {
                        let blend = u * u * (3.0 - 2.0 * u);
                        (
                            left.value + delta * blend,
                            delta * (6.0 * u - 6.0 * u * u) / span,
                            delta * (6.0 - 12.0 * u) / (span * span),
                        )
                    }
                }
            }
        }
    };
    if !value.is_finite()
        || !velocity_per_second.is_finite()
        || !acceleration_per_second2.is_finite()
        || !duration_seconds.is_finite()
    {
        return Err(format!(
            "driver '{}' produced a non-finite sample",
            driver.name
        ));
    }
    Ok(MotionDriverSampleDto {
        driver_id: driver.id,
        joint_id: driver.joint_id,
        coordinate: driver.coordinate,
        value,
        velocity_per_second,
        acceleration_per_second2,
    })
}

fn export_motion_path_csv(
    document: &AssemblyDocumentDto,
    request: MotionPathRequestDto,
    scene: &SolidSceneDto,
) -> Result<String, String> {
    let study = document
        .motion_studies
        .iter()
        .find(|study| study.id == request.study_id)
        .ok_or_else(|| format!("motion study {} does not exist", request.study_id.0))?;
    if !request.sample_rate_hz.is_finite() || !(1.0..=240.0).contains(&request.sample_rate_hz) {
        return Err("motion path sample rate must be between 1 and 240 Hz".to_string());
    }
    let sample_count = (study.duration_seconds * request.sample_rate_hz).ceil() as usize + 1;
    if sample_count > 100_001 {
        return Err("motion path would exceed 100,001 samples".to_string());
    }
    let filter = request
        .occurrence_ids
        .iter()
        .copied()
        .collect::<HashSet<_>>();
    let dt = 1.0 / request.sample_rate_hz;
    let mut csv = String::from("time_seconds,occurrence_id,component_id,x_mm,y_mm,z_mm,qx,qy,qz,qw,linear_speed_mm_s,linear_acceleration_mm_s2,angular_speed_deg_s,angular_acceleration_deg_s2\n");
    let mut previous = HashMap::<OccurrenceId, ([f64; 3], [f64; 4], f64, f64)>::new();
    for index in 0..sample_count {
        let time = (index as f64 * dt).min(study.duration_seconds);
        let sample = document.sample_motion_study(
            SampleMotionStudyRequestDto {
                study_id: study.id,
                time_seconds: time,
            },
            scene,
        )?;
        for pose in sample
            .solution
            .occurrence_poses
            .iter()
            .filter(|pose| filter.is_empty() || filter.contains(&pose.occurrence_id))
        {
            let (linear_speed, linear_acceleration, angular_speed, angular_acceleration) =
                if let Some((last_position, last_rotation, last_linear_speed, last_angular_speed)) =
                    previous.get(&pose.occurrence_id)
                {
                    let step = if index == sample_count - 1 && time < index as f64 * dt {
                        (time - (index as f64 - 1.0) * dt).max(1.0e-9)
                    } else {
                        dt
                    };
                    let linear_speed = length(sub(pose.translation, *last_position)) / step;
                    let angular_speed = (2.0
                        * quaternion_dot(pose.rotation, *last_rotation)
                            .abs()
                            .clamp(-1.0, 1.0)
                            .acos())
                    .to_degrees()
                        / step;
                    (
                        linear_speed,
                        (linear_speed - *last_linear_speed) / step,
                        angular_speed,
                        (angular_speed - *last_angular_speed) / step,
                    )
                } else {
                    (0.0, 0.0, 0.0, 0.0)
                };
            csv.push_str(&format!(
                "{:.9},{},{},{:.9},{:.9},{:.9},{:.12},{:.12},{:.12},{:.12},{:.9},{:.9},{:.9},{:.9}\n",
                time, pose.occurrence_id.0, pose.component_id.0,
                pose.translation[0], pose.translation[1], pose.translation[2],
                pose.rotation[0], pose.rotation[1], pose.rotation[2], pose.rotation[3],
                linear_speed, linear_acceleration, angular_speed, angular_acceleration,
            ));
            previous.insert(
                pose.occurrence_id,
                (pose.translation, pose.rotation, linear_speed, angular_speed),
            );
        }
    }
    Ok(csv)
}

/// Browser/development fallback for hosts without OCCT. Native desktop never
/// calls this path: it evaluates the same request against exact placed B-reps.
pub fn approximate_interference_report(
    scene: &SolidSceneDto,
    poses: &[InstanceBodyPoseDto],
    request: &InterferenceCheckRequestDto,
) -> Result<InterferenceReportDto, String> {
    if !request.clearance_threshold_mm.is_finite() || request.clearance_threshold_mm < 0.0 {
        return Err("interference clearance must be finite and non-negative".to_string());
    }
    let mut pairs = Vec::new();
    for (a_index, b_index) in broad_phase_interference_pairs(scene, poses, request)? {
        pairs.push(approximate_pair_result(
            scene,
            &poses[a_index],
            &poses[b_index],
            request.clearance_threshold_mm,
        )?);
    }
    Ok(InterferenceReportDto {
        exact: false,
        pairs,
    })
}

#[derive(Debug, Clone, Copy)]
struct PlacedBounds {
    pose_index: usize,
    minimum: [f64; 3],
    maximum: [f64; 3],
}

fn placed_body_bounds(
    scene: &SolidSceneDto,
    pose_index: usize,
    pose: &InstanceBodyPoseDto,
) -> Result<PlacedBounds, String> {
    let body = scene
        .bodies
        .iter()
        .find(|body| body.id == pose.body_id)
        .ok_or_else(|| format!("body {} is missing", pose.body_id.0))?;
    if body.mesh.positions.is_empty() {
        return Err(format!("body {} has no display mesh", pose.body_id.0));
    }
    let mut minimum = [f64::INFINITY; 3];
    let mut maximum = [f64::NEG_INFINITY; 3];
    for point in body.mesh.positions.chunks_exact(3) {
        let transformed = add(
            rotate(
                pose.rotation,
                [point[0] as f64, point[1] as f64, point[2] as f64],
            ),
            pose.translation,
        );
        for axis in 0..3 {
            minimum[axis] = minimum[axis].min(transformed[axis]);
            maximum[axis] = maximum[axis].max(transformed[axis]);
        }
    }
    Ok(PlacedBounds {
        pose_index,
        minimum,
        maximum,
    })
}

fn bounds_separation_squared(a: &PlacedBounds, b: &PlacedBounds) -> f64 {
    (0..3)
        .map(|axis| {
            if a.maximum[axis] < b.minimum[axis] {
                b.minimum[axis] - a.maximum[axis]
            } else if b.maximum[axis] < a.minimum[axis] {
                a.minimum[axis] - b.maximum[axis]
            } else {
                0.0
            }
        })
        .map(|gap| gap * gap)
        .sum()
}

/// Return only occurrence pairs whose transformed mesh bounds can overlap or
/// violate the requested clearance. The x-axis sweep makes well-separated
/// large assemblies close to O(n log n); OCCT hosts can then reserve exact
/// B-rep distance/boolean work for this conservative candidate set.
pub fn broad_phase_interference_pairs(
    scene: &SolidSceneDto,
    poses: &[InstanceBodyPoseDto],
    request: &InterferenceCheckRequestDto,
) -> Result<Vec<(usize, usize)>, String> {
    if !request.clearance_threshold_mm.is_finite() || request.clearance_threshold_mm < 0.0 {
        return Err("interference clearance must be finite and non-negative".to_string());
    }
    let filter = request
        .occurrence_ids
        .iter()
        .copied()
        .collect::<HashSet<_>>();
    let mut bounds = poses
        .iter()
        .enumerate()
        .filter(|(_, pose)| {
            pose.visible && (filter.is_empty() || filter.contains(&pose.occurrence_id))
        })
        .map(|(index, pose)| placed_body_bounds(scene, index, pose))
        .collect::<Result<Vec<_>, _>>()?;
    bounds.sort_by(|a, b| a.minimum[0].total_cmp(&b.minimum[0]));

    let threshold = request.clearance_threshold_mm;
    let threshold_squared = threshold * threshold + 1.0e-12;
    let mut candidates = Vec::new();
    for (index, a) in bounds.iter().enumerate() {
        for b in bounds.iter().skip(index + 1) {
            if b.minimum[0] - a.maximum[0] > threshold {
                break;
            }
            if poses[a.pose_index].occurrence_id == poses[b.pose_index].occurrence_id {
                continue;
            }
            if bounds_separation_squared(a, b) <= threshold_squared {
                candidates.push((a.pose_index, b.pose_index));
            }
        }
    }
    Ok(candidates)
}

pub fn approximate_pair_result(
    scene: &SolidSceneDto,
    a: &InstanceBodyPoseDto,
    b: &InstanceBodyPoseDto,
    clearance_threshold_mm: f64,
) -> Result<InterferencePairResultDto, String> {
    let bounds_a = placed_body_bounds(scene, 0, a)?;
    let bounds_b = placed_body_bounds(scene, 1, b)?;
    let (min_a, max_a) = (bounds_a.minimum, bounds_a.maximum);
    let (min_b, max_b) = (bounds_b.minimum, bounds_b.maximum);
    let mut overlap = [0.0; 3];
    let mut gaps = [0.0; 3];
    let mut closest_a = [0.0; 3];
    let mut closest_b = [0.0; 3];
    for axis in 0..3 {
        overlap[axis] = (max_a[axis].min(max_b[axis]) - min_a[axis].max(min_b[axis])).max(0.0);
        if max_a[axis] < min_b[axis] {
            gaps[axis] = min_b[axis] - max_a[axis];
            closest_a[axis] = max_a[axis];
            closest_b[axis] = min_b[axis];
        } else if max_b[axis] < min_a[axis] {
            gaps[axis] = min_a[axis] - max_b[axis];
            closest_a[axis] = min_a[axis];
            closest_b[axis] = max_b[axis];
        } else {
            let shared = (min_a[axis].max(min_b[axis]) + max_a[axis].min(max_b[axis])) * 0.5;
            closest_a[axis] = shared;
            closest_b[axis] = shared;
        }
    }
    let minimum_clearance_mm = length(gaps);
    let overlap_volume_mm3 = overlap[0] * overlap[1] * overlap[2];
    Ok(InterferencePairResultDto {
        occurrence_a: a.occurrence_id,
        body_a: a.body_id,
        occurrence_b: b.occurrence_id,
        body_b: b.body_id,
        minimum_clearance_mm,
        overlap_volume_mm3,
        closest_point_a: closest_a,
        closest_point_b: closest_b,
        interfering: overlap_volume_mm3 > 1.0e-7,
        below_clearance: minimum_clearance_mm <= clearance_threshold_mm + 1.0e-7,
    })
}

/// Positive values mean a configured contact has been violated. Exact touch
/// at zero clearance (or exact satisfaction of a positive clearance) remains
/// zero, so a motion study may start on a physical stop without being treated
/// as already penetrated.
pub fn contact_violation_score(
    result: &InterferencePairResultDto,
    required_clearance_mm: f64,
) -> f64 {
    if result.overlap_volume_mm3 > 1.0e-7 {
        required_clearance_mm + result.overlap_volume_mm3.cbrt()
    } else {
        (required_clearance_mm - result.minimum_clearance_mm).max(0.0)
    }
}

fn active_coordinates(kind: JointKindDto) -> &'static [JointCoordinate] {
    use JointCoordinate::*;
    match kind {
        JointKindDto::Rigid => &[],
        JointKindDto::Revolute | JointKindDto::Screw => &[PrimaryAngle],
        JointKindDto::Slider => &[PrimaryLinear],
        JointKindDto::Cylindrical | JointKindDto::PinSlot => &[PrimaryAngle, PrimaryLinear],
        JointKindDto::Planar => &[PrimaryAngle, PrimaryLinear, SecondaryLinear],
        JointKindDto::Ball => &[PrimaryAngle, SecondaryAngle, TertiaryAngle],
        JointKindDto::Universal => &[PrimaryAngle, SecondaryAngle],
    }
}

fn coordinate_value(joint: &JointDefinitionDto, coordinate: JointCoordinate) -> f64 {
    match coordinate {
        JointCoordinate::PrimaryAngle => joint.angle_offset_deg,
        JointCoordinate::SecondaryAngle => joint.advanced.secondary_angle_offset_deg,
        JointCoordinate::TertiaryAngle => joint.advanced.tertiary_angle_offset_deg,
        JointCoordinate::PrimaryLinear => joint.linear_offset_mm,
        JointCoordinate::SecondaryLinear => joint.advanced.secondary_linear_offset_mm,
    }
}

fn coordinate_limits(
    joint: &JointDefinitionDto,
    coordinate: JointCoordinate,
) -> Option<JointLimitsDto> {
    match coordinate {
        JointCoordinate::PrimaryAngle => effective_angle_limits(joint),
        JointCoordinate::SecondaryAngle => joint.advanced.secondary_angle_limits,
        JointCoordinate::TertiaryAngle => joint.advanced.tertiary_angle_limits,
        JointCoordinate::PrimaryLinear => effective_linear_limits(joint),
        JointCoordinate::SecondaryLinear => joint.advanced.secondary_linear_limits,
    }
}

fn set_coordinate_value(joint: &mut JointDefinitionDto, coordinate: JointCoordinate, value: f64) {
    match coordinate {
        JointCoordinate::PrimaryAngle => joint.angle_offset_deg = value,
        JointCoordinate::SecondaryAngle => joint.advanced.secondary_angle_offset_deg = value,
        JointCoordinate::TertiaryAngle => joint.advanced.tertiary_angle_offset_deg = value,
        JointCoordinate::PrimaryLinear => joint.linear_offset_mm = value,
        JointCoordinate::SecondaryLinear => joint.advanced.secondary_linear_offset_mm = value,
    }
}

fn coordinate_label(coordinate: JointCoordinate) -> &'static str {
    match coordinate {
        JointCoordinate::PrimaryAngle => "primary angle",
        JointCoordinate::SecondaryAngle => "secondary angle",
        JointCoordinate::TertiaryAngle => "tertiary angle",
        JointCoordinate::PrimaryLinear => "primary position",
        JointCoordinate::SecondaryLinear => "secondary position",
    }
}

fn apply_motion_state(
    joint: &mut JointDefinitionDto,
    motion: JointMotionStateDto,
) -> Result<(), String> {
    if motion.joint_id != joint.id {
        return Err(format!(
            "motion for joint {} cannot update joint {}",
            motion.joint_id.0, joint.id.0
        ));
    }
    let values = [
        (JointCoordinate::PrimaryAngle, motion.angle_offset_deg),
        (
            JointCoordinate::SecondaryAngle,
            motion.secondary_angle_offset_deg,
        ),
        (
            JointCoordinate::TertiaryAngle,
            motion.tertiary_angle_offset_deg,
        ),
        (JointCoordinate::PrimaryLinear, motion.linear_offset_mm),
        (
            JointCoordinate::SecondaryLinear,
            motion.secondary_linear_offset_mm,
        ),
    ];
    if values.iter().any(|(_, value)| !value.is_finite()) {
        return Err("joint motion values must be finite".to_string());
    }
    let active = active_coordinates(joint.kind);
    for (coordinate, value) in values {
        if active.contains(&coordinate) {
            ensure_motion_in_limits(
                &joint.name,
                coordinate_label(coordinate),
                value,
                coordinate_limits(joint, coordinate),
            )?;
            set_coordinate_value(joint, coordinate, value);
        }
    }
    Ok(())
}

fn effective_angle_limits(joint: &JointDefinitionDto) -> Option<JointLimitsDto> {
    joint.angle_limits.or_else(|| {
        matches!(joint.kind, JointKindDto::Revolute | JointKindDto::Screw)
            .then_some(joint.limits)
            .flatten()
    })
}

fn effective_linear_limits(joint: &JointDefinitionDto) -> Option<JointLimitsDto> {
    joint.linear_limits.or_else(|| {
        (joint.kind == JointKindDto::Slider)
            .then_some(joint.limits)
            .flatten()
    })
}

fn ensure_motion_in_limits(
    joint_name: &str,
    label: &str,
    value: f64,
    limits: Option<JointLimitsDto>,
) -> Result<(), String> {
    if let Some(limits) = limits {
        if value < limits.min || value > limits.max {
            return Err(format!(
                "joint '{joint_name}' {label} {value} is outside [{}, {}]",
                limits.min, limits.max
            ));
        }
    }
    Ok(())
}

fn clamp_motion_value(
    joint: &JointDefinitionDto,
    label: &str,
    value: f64,
    limits: Option<JointLimitsDto>,
    diagnostics: &mut Vec<AssemblyDiagnosticDto>,
) -> f64 {
    let Some(limits) = limits else {
        return value;
    };
    let clamped = value.clamp(limits.min, limits.max);
    if clamped != value {
        diagnostics.push(AssemblyDiagnosticDto {
            kind: AssemblyDiagnosticKindDto::LimitViolation,
            message: format!(
                "Joint '{}' {label} {value} was clamped to {clamped}",
                joint.name
            ),
            joint_id: Some(joint.id),
            body_id: None,
        });
    }
    clamped
}

fn joint_motion_pose(
    joint: &JointDefinitionDto,
    diagnostics: &mut Vec<AssemblyDiagnosticDto>,
) -> RigidPose {
    let mut value = |coordinate| {
        clamp_motion_value(
            joint,
            coordinate_label(coordinate),
            coordinate_value(joint, coordinate),
            coordinate_limits(joint, coordinate),
            diagnostics,
        )
    };
    let angle = value(JointCoordinate::PrimaryAngle).to_radians();
    let secondary_angle = value(JointCoordinate::SecondaryAngle).to_radians();
    let tertiary_angle = value(JointCoordinate::TertiaryAngle).to_radians();
    let linear = value(JointCoordinate::PrimaryLinear);
    let secondary_linear = value(JointCoordinate::SecondaryLinear);
    match joint.kind {
        JointKindDto::Rigid => RigidPose::IDENTITY,
        JointKindDto::Revolute => RigidPose::rotation([0.0, 0.0, 1.0], angle),
        JointKindDto::Slider => RigidPose::translation([0.0, 0.0, linear]),
        JointKindDto::Cylindrical => RigidPose::translation([0.0, 0.0, linear])
            .compose(RigidPose::rotation([0.0, 0.0, 1.0], angle)),
        JointKindDto::Planar => RigidPose::translation([linear, secondary_linear, 0.0])
            .compose(RigidPose::rotation([0.0, 0.0, 1.0], angle)),
        JointKindDto::Ball => RigidPose::rotation([0.0, 0.0, 1.0], angle)
            .compose(RigidPose::rotation([0.0, 1.0, 0.0], secondary_angle))
            .compose(RigidPose::rotation([1.0, 0.0, 0.0], tertiary_angle)),
        JointKindDto::PinSlot => RigidPose::translation([linear, 0.0, 0.0])
            .compose(RigidPose::rotation([0.0, 0.0, 1.0], angle)),
        JointKindDto::Screw => {
            let linear =
                angle / (std::f64::consts::PI * 2.0) * joint.advanced.screw_pitch_mm_per_revolution;
            RigidPose::translation([0.0, 0.0, linear])
                .compose(RigidPose::rotation([0.0, 0.0, 1.0], angle))
        }
        JointKindDto::Universal => RigidPose::rotation([1.0, 0.0, 0.0], angle)
            .compose(RigidPose::rotation([0.0, 1.0, 0.0], secondary_angle)),
    }
}

fn solve_edges(
    document: &AssemblyDocumentDto,
    scene: &SolidSceneDto,
    diagnostics: &mut Vec<AssemblyDiagnosticDto>,
) -> Vec<SolveEdge> {
    let mut edges = Vec::new();
    for joint in document.joints.iter().filter(|joint| joint.enabled) {
        let connector_a = canonical_connector_against_scene(&joint.connector_a, scene);
        let connector_b = canonical_connector_against_scene(&joint.connector_b, scene);
        let (connector_a, connector_b) = match (connector_a, connector_b) {
            (Ok(a), Ok(b)) => (a, b),
            (Err(error), _) | (_, Err(error)) => {
                diagnostics.push(AssemblyDiagnosticDto {
                    kind: AssemblyDiagnosticKindDto::BrokenReference,
                    message: format!("Joint '{}': {error}", joint.name),
                    joint_id: Some(joint.id),
                    body_id: None,
                });
                continue;
            }
        };
        let (Some(occurrence_a), Some(occurrence_b)) = (
            joint.advanced.connector_a_occurrence_id,
            joint.advanced.connector_b_occurrence_id,
        ) else {
            diagnostics.push(AssemblyDiagnosticDto {
                kind: AssemblyDiagnosticKindDto::BrokenReference,
                message: format!("Joint '{}' has no component occurrence binding", joint.name),
                joint_id: Some(joint.id),
                body_id: None,
            });
            continue;
        };
        if let Err(error) = validate_occurrence_pair(
            &document.component_structure,
            occurrence_a,
            connector_a.body_id,
            occurrence_b,
            connector_b.body_id,
        ) {
            diagnostics.push(AssemblyDiagnosticDto {
                kind: AssemblyDiagnosticKindDto::BrokenReference,
                message: format!("Joint '{}': {error}", joint.name),
                joint_id: Some(joint.id),
                body_id: None,
            });
            continue;
        }
        let component_a = document
            .component_structure
            .occurrence(occurrence_a)
            .and_then(|occurrence| {
                document
                    .component_structure
                    .definition(occurrence.component_id)
            })
            .expect("validated occurrence A component");
        let component_b = document
            .component_structure
            .occurrence(occurrence_b)
            .and_then(|occurrence| {
                document
                    .component_structure
                    .definition(occurrence.component_id)
            })
            .expect("validated occurrence B component");
        let frame_a = RigidPose::from_transform(component_a.local_coordinate_system)
            .inverse()
            .compose(RigidPose::from_frame(connector_a.frame))
            .compose(RigidPose::rotation(
                [0.0, 0.0, 1.0],
                joint.advanced.connector_a_twist_deg.to_radians(),
            ));
        let frame_b = RigidPose::from_transform(component_b.local_coordinate_system)
            .inverse()
            .compose(RigidPose::from_frame(connector_b.frame))
            .compose(RigidPose::rotation(
                [0.0, 0.0, 1.0],
                joint.advanced.connector_b_twist_deg.to_radians(),
            ));
        let motion = joint_motion_pose(joint, diagnostics);
        // Planar connector normals oppose one another by default. Flipped
        // requests intentionally keep their normals aligned.
        let mate = if joint.flipped {
            RigidPose::IDENTITY
        } else {
            RigidPose::rotation([1.0, 0.0, 0.0], std::f64::consts::PI)
        };
        edges.push(SolveEdge {
            joint_id: joint.id,
            a: occurrence_a,
            b: occurrence_b,
            a_to_b: frame_a
                .compose(motion)
                .compose(mate)
                .compose(frame_b.inverse()),
        });
    }
    edges.sort_by_key(|edge| edge.joint_id.0);
    edges
}

fn solve_assembly(document: &AssemblyDocumentDto, scene: &SolidSceneDto) -> AssemblySolutionDto {
    let mut document = document.clone();
    let mut diagnostics = Vec::new();
    if let Err(error) = document.project_active_scene(scene) {
        diagnostics.push(AssemblyDiagnosticDto {
            kind: AssemblyDiagnosticKindDto::BrokenReference,
            message: format!("Component structure: {error}"),
            joint_id: None,
            body_id: None,
        });
    }
    let edges = solve_edges(&document, scene, &mut diagnostics);
    for relation in &document.gear_relations {
        if relation
            .error_deg(&document)
            .is_some_and(|error| error.abs() > 1e-5)
        {
            diagnostics.push(AssemblyDiagnosticDto {
                kind: AssemblyDiagnosticKindDto::CycleConflict,
                message: format!(
                    "Gear relation '{}' has inconsistent unwrapped angles",
                    relation.name
                ),
                joint_id: Some(relation.joint_a),
                body_id: None,
            });
        }
    }
    let mut occurrence_poses = HashMap::<OccurrenceId, RigidPose>::new();
    let mut occurrence_visibility = HashMap::<OccurrenceId, bool>::new();
    let mut conflict_joints = HashSet::new();
    solve_occurrence_group(
        None,
        RigidPose::IDENTITY,
        true,
        &document.component_structure,
        &edges,
        &mut occurrence_poses,
        &mut occurrence_visibility,
        &mut diagnostics,
        &mut conflict_joints,
    );

    let mut occurrence_pose_rows = document
        .component_structure
        .occurrences
        .iter()
        .filter_map(|occurrence| {
            occurrence_poses
                .get(&occurrence.id)
                .map(|pose| OccurrencePoseDto {
                    occurrence_id: occurrence.id,
                    component_id: occurrence.component_id,
                    translation: pose.translation,
                    rotation: pose.rotation,
                })
        })
        .collect::<Vec<_>>();
    occurrence_pose_rows.sort_by_key(|pose| pose.occurrence_id.0);

    let live_body_ids = scene
        .bodies
        .iter()
        .map(|body| body.id)
        .collect::<HashSet<_>>();
    let mut instance_body_poses = Vec::new();
    for occurrence in &document.component_structure.occurrences {
        let Some(world_pose) = occurrence_poses.get(&occurrence.id).copied() else {
            continue;
        };
        let Some(component) = document
            .component_structure
            .definition(occurrence.component_id)
        else {
            continue;
        };
        let display_pose = world_pose
            .compose(RigidPose::from_transform(component.local_coordinate_system).inverse());
        for body_id in &component.body_ids {
            if !live_body_ids.contains(body_id) {
                diagnostics.push(AssemblyDiagnosticDto {
                    kind: AssemblyDiagnosticKindDto::BrokenReference,
                    message: format!(
                        "Component '{}' references missing body {}",
                        component.name, body_id.0
                    ),
                    joint_id: None,
                    body_id: Some(*body_id),
                });
                continue;
            }
            instance_body_poses.push(InstanceBodyPoseDto {
                occurrence_id: occurrence.id,
                component_id: component.id,
                body_id: *body_id,
                translation: display_pose.translation,
                rotation: display_pose.rotation,
                visible: occurrence_visibility
                    .get(&occurrence.id)
                    .copied()
                    .unwrap_or(occurrence.visible),
            });
        }
    }
    instance_body_poses.sort_by_key(|pose| (pose.occurrence_id.0, pose.body_id.0));

    // Legacy callers still receive one deterministic pose per source body.
    // New renderers and pickers consume `instance_body_poses` and can display
    // every reusable occurrence simultaneously.
    let mut body_ids = scene.bodies.iter().map(|body| body.id).collect::<Vec<_>>();
    body_ids.sort_by_key(|body_id| body_id.0);
    let body_poses = body_ids
        .into_iter()
        .map(|body_id| {
            let pose = instance_body_poses
                .iter()
                .find(|pose| pose.body_id == body_id)
                .map(|pose| RigidPose {
                    translation: pose.translation,
                    rotation: pose.rotation,
                })
                .unwrap_or(RigidPose::IDENTITY);
            BodyPoseDto {
                body_id,
                translation: pose.translation,
                rotation: pose.rotation,
            }
        })
        .collect();
    let solved = !diagnostics.iter().any(|diagnostic| {
        matches!(
            diagnostic.kind,
            AssemblyDiagnosticKindDto::BrokenReference | AssemblyDiagnosticKindDto::CycleConflict
        )
    });
    AssemblySolutionDto {
        body_poses,
        occurrence_poses: occurrence_pose_rows,
        instance_body_poses,
        diagnostics,
        solved,
    }
}

#[allow(clippy::too_many_arguments)]
fn solve_occurrence_group(
    parent_occurrence_id: Option<OccurrenceId>,
    parent_world_pose: RigidPose,
    parent_visible: bool,
    structure: &ComponentStructureDto,
    edges: &[SolveEdge],
    occurrence_poses: &mut HashMap<OccurrenceId, RigidPose>,
    occurrence_visibility: &mut HashMap<OccurrenceId, bool>,
    diagnostics: &mut Vec<AssemblyDiagnosticDto>,
    conflict_joints: &mut HashSet<JointId>,
) {
    let mut siblings = structure
        .occurrences
        .iter()
        .filter(|occurrence| occurrence.parent_occurrence_id == parent_occurrence_id)
        .collect::<Vec<_>>();
    siblings.sort_by_key(|occurrence| occurrence.id.0);
    if siblings.is_empty() {
        return;
    }
    let sibling_ids = siblings
        .iter()
        .map(|occurrence| occurrence.id)
        .collect::<HashSet<_>>();
    let mut local_poses = HashMap::<OccurrenceId, RigidPose>::new();
    let explicit_ground = siblings
        .iter()
        .find(|occurrence| occurrence.grounded)
        .map(|occurrence| occurrence.id);
    let temporary_ground =
        explicit_ground.or_else(|| siblings.first().map(|occurrence| occurrence.id));
    let mut seeds = Vec::new();
    if let Some(ground) = temporary_ground {
        seeds.push((ground, true));
    }
    seeds.extend(
        siblings
            .iter()
            .map(|occurrence| occurrence.id)
            .filter(|occurrence_id| Some(*occurrence_id) != temporary_ground)
            .map(|occurrence_id| (occurrence_id, false)),
    );

    for (seed, grounded_cluster) in seeds {
        if local_poses.contains_key(&seed) {
            continue;
        }
        let authored_pose = structure
            .occurrence(seed)
            .map(|occurrence| RigidPose::from_transform(occurrence.local_pose))
            .unwrap_or(RigidPose::IDENTITY);
        local_poses.insert(seed, authored_pose);
        if !grounded_cluster {
            let body_id = structure
                .occurrence(seed)
                .and_then(|occurrence| structure.definition(occurrence.component_id))
                .and_then(|definition| definition.body_ids.first().copied());
            diagnostics.push(AssemblyDiagnosticDto {
                kind: AssemblyDiagnosticKindDto::FreeComponent,
                message: format!(
                    "Occurrence {} belongs to an ungrounded mechanism; its authored placement remains free",
                    seed.0
                ),
                joint_id: None,
                body_id,
            });
        }
        let mut queue = VecDeque::from([seed]);
        while let Some(current) = queue.pop_front() {
            let current_pose = local_poses[&current];
            for edge in edges
                .iter()
                .filter(|edge| sibling_ids.contains(&edge.a) && sibling_ids.contains(&edge.b))
            {
                let (next, relation) = if edge.a == current {
                    (edge.b, edge.a_to_b)
                } else if edge.b == current {
                    (edge.a, edge.a_to_b.inverse())
                } else {
                    continue;
                };
                let candidate = current_pose.compose(relation);
                if let Some(existing) = local_poses.get(&next) {
                    if !existing.approximately_eq(candidate)
                        && conflict_joints.insert(edge.joint_id)
                    {
                        let body_id = structure
                            .occurrence(next)
                            .and_then(|occurrence| structure.definition(occurrence.component_id))
                            .and_then(|definition| definition.body_ids.first().copied());
                        diagnostics.push(AssemblyDiagnosticDto {
                            kind: AssemblyDiagnosticKindDto::CycleConflict,
                            message: format!(
                                "Joint {} closes an inconsistent kinematic loop",
                                edge.joint_id.0
                            ),
                            joint_id: Some(edge.joint_id),
                            body_id,
                        });
                    }
                } else {
                    local_poses.insert(next, candidate);
                    queue.push_back(next);
                }
            }
        }
    }

    for sibling in siblings {
        let local_pose = local_poses
            .get(&sibling.id)
            .copied()
            .unwrap_or_else(|| RigidPose::from_transform(sibling.local_pose));
        let world_pose = parent_world_pose.compose(local_pose);
        occurrence_poses.insert(sibling.id, world_pose);
        let visible = parent_visible && sibling.visible;
        occurrence_visibility.insert(sibling.id, visible);
        solve_occurrence_group(
            Some(sibling.id),
            world_pose,
            visible,
            structure,
            edges,
            occurrence_poses,
            occurrence_visibility,
            diagnostics,
            conflict_joints,
        );
    }
}

fn solve_mechanism_drag(
    document: &AssemblyDocumentDto,
    request: MechanismDragRequestDto,
    scene: &SolidSceneDto,
) -> Result<MechanismPreviewDto, String> {
    solve_mechanism_coordinates(document, request, scene, &[], false)
}

fn solve_mechanism_coordinates(
    document: &AssemblyDocumentDto,
    request: MechanismDragRequestDto,
    scene: &SolidSceneDto,
    held: &[(JointId, JointCoordinate)],
    closure_only: bool,
) -> Result<MechanismPreviewDto, String> {
    if !scene.bodies.iter().any(|body| body.id == request.body_id) {
        return Err(format!("body {} does not exist", request.body_id.0));
    }
    if request.target_pose.body_id != request.body_id {
        return Err("mechanism target pose must reference the dragged body".to_string());
    }
    if !request
        .target_pose
        .translation
        .into_iter()
        .all(f64::is_finite)
        || !request.target_pose.rotation.into_iter().all(f64::is_finite)
        || quaternion_dot(request.target_pose.rotation, request.target_pose.rotation) <= 1.0e-12
    {
        return Err("mechanism target pose must be finite".to_string());
    }
    if request.grab_point_local.is_some() != request.target_point_world.is_some() {
        return Err(
            "mechanism drag grab point and world target must be supplied together".to_string(),
        );
    }
    if request
        .grab_point_local
        .into_iter()
        .chain(request.target_point_world)
        .flatten()
        .any(|value| !value.is_finite())
    {
        return Err("mechanism drag points must be finite".to_string());
    }
    let mut candidate = document.clone();
    candidate.project_active_scene(scene)?;
    if !request.initial_joint_motions.is_empty() {
        candidate.apply_joint_motions(&request.initial_joint_motions)?;
    }
    let target_occurrence = request
        .occurrence_id
        .or_else(|| {
            candidate
                .component_structure
                .occurrence_for_body(request.body_id)
        })
        .ok_or_else(|| "dragged body has no component occurrence".to_string())?;
    if !candidate
        .component_structure
        .occurrence_contains_body(target_occurrence, request.body_id)
    {
        return Err("dragged occurrence does not contain the requested body".to_string());
    }
    let parent = candidate
        .component_structure
        .occurrence(target_occurrence)
        .and_then(|occurrence| occurrence.parent_occurrence_id);
    let mut siblings = candidate
        .component_structure
        .occurrences
        .iter()
        .filter(|occurrence| occurrence.parent_occurrence_id == parent)
        .collect::<Vec<_>>();
    siblings.sort_by_key(|occurrence| occurrence.id.0);
    let ground = siblings
        .iter()
        .find(|occurrence| occurrence.grounded)
        .or_else(|| siblings.first())
        .map(|occurrence| occurrence.id)
        .ok_or_else(|| "mechanism has no occurrence in the dragged subassembly".to_string())?;
    if target_occurrence == ground && !closure_only {
        return Err("the grounded component cannot be dragged".to_string());
    }
    joint_path(&candidate, ground, target_occurrence).ok_or_else(|| {
        "the dragged component is not connected to the grounded component".to_string()
    })?;
    // A serial-chain-only variable set cannot close a redundant mechanism:
    // one path reaches the target while the remaining edge is left as a
    // CycleConflict. Optimise every free coordinate in the connected sibling
    // mechanism and add explicit closure residuals for every saved edge.
    let mechanism_ids = connected_joint_ids(&candidate, ground);
    let mut variables = Vec::<(JointId, JointCoordinate)>::new();
    for joint in candidate
        .joints
        .iter()
        .filter(|joint| joint.enabled && mechanism_ids.contains(&joint.id))
    {
        variables.extend(
            active_coordinates(joint.kind)
                .iter()
                .copied()
                .map(|coordinate| (joint.id, coordinate))
                .filter(|coordinate| !held.contains(coordinate)),
        );
    }

    let target = RigidPose {
        translation: request.target_pose.translation,
        rotation: normalize_quaternion(request.target_pose.rotation),
    };
    let point_target = request.grab_point_local.zip(request.target_point_world);
    let maximum_iterations = request.maximum_iterations.clamp(1, 96);
    let mut iterations = 0;
    let mut converged = false;
    let mut position_error_mm = f64::INFINITY;
    let mut orientation_error_deg = f64::INFINITY;

    if !variables.is_empty() {
        for iteration in 0..maximum_iterations {
            iterations = iteration + 1;
            let residual_state = mechanism_residual(
                &candidate,
                scene,
                target_occurrence,
                target,
                point_target,
                &mechanism_ids,
                closure_only,
            )?;
            let residual = residual_state.values;
            position_error_mm = residual_state.position_error_mm;
            orientation_error_deg = residual_state.orientation_error_deg;
            if position_error_mm <= 0.02
                && (!request.solve_orientation || orientation_error_deg <= 0.15)
                && residual_state.maximum_loop_position_error_mm <= 1.0e-5
                && residual_state.maximum_loop_orientation_error_deg <= 0.01
                && residual_state.maximum_gear_error_deg <= 1.0e-5
            {
                converged = true;
                break;
            }

            let mut jacobian = vec![vec![0.0; variables.len()]; residual.len()];
            for (column, (joint_id, coordinate)) in variables.iter().copied().enumerate() {
                let base_value = candidate
                    .joints
                    .iter()
                    .find(|joint| joint.id == joint_id)
                    .map(|joint| coordinate_value(joint, coordinate))
                    .ok_or_else(|| format!("joint {} disappeared during solve", joint_id.0))?;
                let epsilon = match coordinate {
                    JointCoordinate::PrimaryAngle
                    | JointCoordinate::SecondaryAngle
                    | JointCoordinate::TertiaryAngle => 1.0e-3,
                    JointCoordinate::PrimaryLinear | JointCoordinate::SecondaryLinear => 0.02,
                };
                let mut perturbed = candidate.clone();
                let joint = perturbed
                    .joints
                    .iter_mut()
                    .find(|joint| joint.id == joint_id)
                    .expect("candidate joint exists");
                let mut next_value = clamp_coordinate(joint, coordinate, base_value + epsilon);
                if (next_value - base_value).abs() <= 1.0e-12 {
                    next_value = clamp_coordinate(joint, coordinate, base_value - epsilon);
                }
                let actual_step = next_value - base_value;
                if actual_step.abs() <= 1.0e-12 {
                    continue;
                }
                set_coordinate_value(joint, coordinate, next_value);
                let next_residual = mechanism_residual(
                    &perturbed,
                    scene,
                    target_occurrence,
                    target,
                    point_target,
                    &mechanism_ids,
                    closure_only,
                )?
                .values;
                for row in 0..residual.len() {
                    jacobian[row][column] = (next_residual[row] - residual[row]) / actual_step;
                }
            }

            let damping = 1.0e-4;
            let mut normal = vec![vec![0.0; variables.len()]; variables.len()];
            let mut rhs = vec![0.0; variables.len()];
            for row in 0..residual.len() {
                let weight = mechanism_residual_weight(row, request.solve_orientation);
                for column in 0..variables.len() {
                    rhs[column] -= jacobian[row][column] * residual[row] * weight;
                    for other in 0..variables.len() {
                        normal[column][other] +=
                            jacobian[row][column] * jacobian[row][other] * weight;
                    }
                }
            }
            for index in 0..variables.len() {
                normal[index][index] += damping;
            }
            let delta = solve_linear_system(normal, rhs);
            // Backtrack the locally linear Gauss-Newton step. Without this,
            // long serial chains can overshoot the quaternion branch and
            // monotonically drive every revolute coordinate into its limit.
            let objective = weighted_mechanism_residual(&residual, request.solve_orientation);
            let mut accepted = None;
            if delta
                .as_ref()
                .is_some_and(|values| values.iter().any(|value| value.abs() > 1.0e-8))
            {
                let delta = delta.as_ref().expect("non-zero delta exists");
                for step_scale in [1.0, 0.5, 0.25, 0.125, 0.0625, 0.03125] {
                    let mut trial = candidate.clone();
                    for ((joint_id, coordinate), delta) in
                        variables.iter().copied().zip(delta.iter().copied())
                    {
                        let joint = trial
                            .joints
                            .iter_mut()
                            .find(|joint| joint.id == joint_id)
                            .expect("candidate joint exists");
                        let maximum_step = match coordinate {
                            JointCoordinate::PrimaryAngle
                            | JointCoordinate::SecondaryAngle
                            | JointCoordinate::TertiaryAngle => 20.0,
                            JointCoordinate::PrimaryLinear | JointCoordinate::SecondaryLinear => {
                                8.0
                            }
                        };
                        let step = delta.clamp(-maximum_step, maximum_step) * step_scale;
                        let next = clamp_coordinate(
                            joint,
                            coordinate,
                            coordinate_value(joint, coordinate) + step,
                        );
                        set_coordinate_value(joint, coordinate, next);
                    }
                    let trial_residual = mechanism_residual(
                        &trial,
                        scene,
                        target_occurrence,
                        target,
                        point_target,
                        &mechanism_ids,
                        closure_only,
                    )?;
                    let trial_objective = weighted_mechanism_residual(
                        &trial_residual.values,
                        request.solve_orientation,
                    );
                    if trial_objective + 1.0e-12 < objective {
                        accepted = Some(trial);
                        break;
                    }
                }
            }
            if let Some(next_candidate) = accepted {
                candidate = next_candidate;
                continue;
            }

            // At a straight-link singularity the pointer error can be
            // orthogonal to every first-order Jacobian column, producing a
            // zero Gauss-Newton step even though bending either adjacent
            // joint would move toward the target. Probe a small deterministic
            // coordinate perturbation only on that stalled path. This is
            // deliberately outside the normal fast path and gives continued
            // dragging a way through a dead-center linkage without requiring
            // the user to release and grab a different material point.
            let mut exploratory: Option<(f64, AssemblyDocumentDto)> = None;
            for (joint_id, coordinate) in variables.iter().copied() {
                for direction in [-1.0, 1.0] {
                    let mut trial = candidate.clone();
                    let joint = trial
                        .joints
                        .iter_mut()
                        .find(|joint| joint.id == joint_id)
                        .expect("candidate joint exists");
                    let step = match coordinate {
                        JointCoordinate::PrimaryAngle
                        | JointCoordinate::SecondaryAngle
                        | JointCoordinate::TertiaryAngle => 2.0,
                        JointCoordinate::PrimaryLinear | JointCoordinate::SecondaryLinear => 0.5,
                    } * direction;
                    let base = coordinate_value(joint, coordinate);
                    let next = clamp_coordinate(joint, coordinate, base + step);
                    if (next - base).abs() <= 1.0e-12 {
                        continue;
                    }
                    set_coordinate_value(joint, coordinate, next);
                    let trial_residual = mechanism_residual(
                        &trial,
                        scene,
                        target_occurrence,
                        target,
                        point_target,
                        &mechanism_ids,
                        closure_only,
                    )?;
                    let trial_objective = weighted_mechanism_residual(
                        &trial_residual.values,
                        request.solve_orientation,
                    );
                    if trial_objective + 1.0e-12 < objective
                        && exploratory
                            .as_ref()
                            .is_none_or(|(best, _)| trial_objective < *best)
                    {
                        exploratory = Some((trial_objective, trial));
                    }
                }
            }
            // A fully extended serial linkage needs two neighboring angular
            // coordinates to leave dead center together: perturbing either
            // joint alone initially moves the grabbed point sideways and can
            // make the objective worse. Probe a small set of coordinated
            // bends (including the 1:-2 relationship of equal-length links)
            // before declaring the pointer target stuck. This remains a rare
            // stalled-path fallback rather than work paid on every frame.
            let angular_variables = variables
                .iter()
                .copied()
                .filter(|(_, coordinate)| {
                    matches!(
                        coordinate,
                        JointCoordinate::PrimaryAngle
                            | JointCoordinate::SecondaryAngle
                            | JointCoordinate::TertiaryAngle
                    )
                })
                .collect::<Vec<_>>();
            for pair in angular_variables.windows(2) {
                for (first_step, second_step) in [
                    (1.0, -2.0),
                    (2.0, -1.0),
                    (-1.0, 2.0),
                    (-2.0, 1.0),
                    (1.0, 2.0),
                    (2.0, 1.0),
                    (-1.0, -2.0),
                    (-2.0, -1.0),
                ] {
                    let mut trial = candidate.clone();
                    let mut changed = true;
                    for ((joint_id, coordinate), step) in
                        pair.iter().copied().zip([first_step, second_step])
                    {
                        let joint = trial
                            .joints
                            .iter_mut()
                            .find(|joint| joint.id == joint_id)
                            .expect("candidate joint exists");
                        let base = coordinate_value(joint, coordinate);
                        let next = clamp_coordinate(joint, coordinate, base + step);
                        changed &= (next - base).abs() > 1.0e-12;
                        set_coordinate_value(joint, coordinate, next);
                    }
                    if !changed {
                        continue;
                    }
                    let trial_residual = mechanism_residual(
                        &trial,
                        scene,
                        target_occurrence,
                        target,
                        point_target,
                        &mechanism_ids,
                        closure_only,
                    )?;
                    let trial_objective = weighted_mechanism_residual(
                        &trial_residual.values,
                        request.solve_orientation,
                    );
                    if trial_objective + 1.0e-12 < objective
                        && exploratory
                            .as_ref()
                            .is_none_or(|(best, _)| trial_objective < *best)
                    {
                        exploratory = Some((trial_objective, trial));
                    }
                }
            }
            let Some((_, next_candidate)) = exploratory else {
                break;
            };
            candidate = next_candidate;
        }
    }

    let mut solution = candidate.solve(scene);
    if let Ok(residual) = mechanism_residual(
        &candidate,
        scene,
        target_occurrence,
        target,
        point_target,
        &mechanism_ids,
        closure_only,
    ) {
        position_error_mm = residual.position_error_mm;
        orientation_error_deg = residual.orientation_error_deg;
        converged = position_error_mm <= 0.05
            && (!request.solve_orientation || orientation_error_deg <= 0.35)
            && residual.maximum_loop_position_error_mm <= 1.0e-5
            && residual.maximum_loop_orientation_error_deg <= 0.01
            && residual.maximum_gear_error_deg <= 1.0e-5;
    }
    if !converged {
        solution.diagnostics.push(AssemblyDiagnosticDto {
            kind: if variables.is_empty() {
                AssemblyDiagnosticKindDto::OverConstrained
            } else {
                AssemblyDiagnosticKindDto::KinematicUnreachable
            },
            message: if variables.is_empty() {
                "The grounded-to-target path has no free degrees of freedom".to_string()
            } else {
                if request.solve_orientation {
                    format!(
                        "Mechanism target remains {:.3} mm and {:.3}° away after {} iterations",
                        position_error_mm, orientation_error_deg, iterations
                    )
                } else {
                    format!(
                        "Mechanism target remains {:.3} mm away after {} iterations",
                        position_error_mm, iterations
                    )
                }
            },
            joint_id: None,
            body_id: Some(request.body_id),
        });
    }
    let joint_motions = candidate
        .joints
        .iter()
        .filter(|joint| mechanism_ids.contains(&joint.id))
        .map(JointMotionStateDto::from_joint)
        .collect();
    Ok(MechanismPreviewDto {
        solution,
        joint_motions,
        converged,
        iterations,
        position_error_mm,
        orientation_error_deg,
    })
}

fn connected_joint_ids(document: &AssemblyDocumentDto, start: OccurrenceId) -> HashSet<JointId> {
    let mut joints = document
        .joints
        .iter()
        .filter(|joint| joint.enabled)
        .collect::<Vec<_>>();
    joints.sort_by_key(|joint| joint.id.0);
    let mut result = HashSet::new();
    let mut visited = HashSet::from([start]);
    let mut queue = VecDeque::from([start]);
    while let Some(occurrence_id) = queue.pop_front() {
        for joint in &joints {
            let next = if joint.advanced.connector_a_occurrence_id == Some(occurrence_id) {
                joint.advanced.connector_b_occurrence_id
            } else if joint.advanced.connector_b_occurrence_id == Some(occurrence_id) {
                joint.advanced.connector_a_occurrence_id
            } else {
                None
            };
            let Some(next) = next else { continue };
            result.insert(joint.id);
            if visited.insert(next) {
                queue.push_back(next);
            }
        }
    }
    result
}

fn mechanism_residual_weight(row: usize, solve_orientation: bool) -> f64 {
    if row < 3 {
        1.0
    } else if row < 6 {
        if solve_orientation {
            18.0
        } else {
            0.0
        }
    } else if (row - 6) % 6 < 3 {
        // Closure is a hard assembly constraint. A higher weight than the
        // pointer target lets redundant coordinates move together instead of
        // tearing the saved loop open.
        64.0
    } else {
        256.0
    }
}

fn weighted_mechanism_residual(residual: &[f64], solve_orientation: bool) -> f64 {
    residual
        .iter()
        .enumerate()
        .map(|(row, value)| mechanism_residual_weight(row, solve_orientation) * value * value)
        .sum()
}

struct MechanismResidual {
    values: Vec<f64>,
    position_error_mm: f64,
    orientation_error_deg: f64,
    maximum_loop_position_error_mm: f64,
    maximum_loop_orientation_error_deg: f64,
    maximum_gear_error_deg: f64,
}

fn mechanism_residual(
    document: &AssemblyDocumentDto,
    scene: &SolidSceneDto,
    target_occurrence: OccurrenceId,
    target: RigidPose,
    point_target: Option<([f64; 3], [f64; 3])>,
    mechanism_joint_ids: &HashSet<JointId>,
    closure_only: bool,
) -> Result<MechanismResidual, String> {
    let solution = document.solve(scene);
    let current = solution_occurrence_pose(&solution, target_occurrence)
        .ok_or_else(|| "dragged component has no solved pose".to_string())?;
    let mut target_residual = pose_residual(current, target);
    if let Some((grab_point_local, target_point_world)) = point_target {
        let current_grab_point = add(
            current.translation,
            rotate(current.rotation, grab_point_local),
        );
        let point_residual = sub(current_grab_point, target_point_world);
        target_residual[..3].copy_from_slice(&point_residual);
    }
    if closure_only {
        target_residual = [0.0; 6];
    }
    let position_error_mm = length([target_residual[0], target_residual[1], target_residual[2]]);
    let orientation_error_deg =
        length([target_residual[3], target_residual[4], target_residual[5]]).to_degrees();
    let mut values = target_residual.to_vec();
    let mut maximum_loop_position_error_mm: f64 = 0.0;
    let mut maximum_loop_orientation_error_deg: f64 = 0.0;
    let mut diagnostics = Vec::new();
    for edge in solve_edges(document, scene, &mut diagnostics)
        .into_iter()
        .filter(|edge| mechanism_joint_ids.contains(&edge.joint_id))
    {
        let Some(pose_a) = solution_occurrence_pose(&solution, edge.a) else {
            continue;
        };
        let Some(pose_b) = solution_occurrence_pose(&solution, edge.b) else {
            continue;
        };
        let closure = pose_residual(pose_b, pose_a.compose(edge.a_to_b));
        maximum_loop_position_error_mm =
            maximum_loop_position_error_mm.max(length([closure[0], closure[1], closure[2]]));
        maximum_loop_orientation_error_deg = maximum_loop_orientation_error_deg
            .max(length([closure[3], closure[4], closure[5]]).to_degrees());
        values.extend_from_slice(&closure);
    }
    let mut maximum_gear_error_deg: f64 = 0.0;
    for relation in &document.gear_relations {
        if mechanism_joint_ids.contains(&relation.joint_a)
            && mechanism_joint_ids.contains(&relation.joint_b)
        {
            if let Some(error) = relation.error_deg(document) {
                maximum_gear_error_deg = maximum_gear_error_deg.max(error.abs());
                values.extend_from_slice(&[0.0, 0.0, 0.0, error.to_radians(), 0.0, 0.0]);
            }
        }
    }
    Ok(MechanismResidual {
        values,
        position_error_mm,
        orientation_error_deg,
        maximum_loop_position_error_mm,
        maximum_loop_orientation_error_deg,
        maximum_gear_error_deg,
    })
}

fn joint_path(
    document: &AssemblyDocumentDto,
    start: OccurrenceId,
    target: OccurrenceId,
) -> Option<Vec<JointId>> {
    let mut joints = document
        .joints
        .iter()
        .filter(|joint| joint.enabled)
        .collect::<Vec<_>>();
    joints.sort_by_key(|joint| joint.id.0);
    let mut previous = HashMap::<OccurrenceId, (OccurrenceId, JointId)>::new();
    let mut visited = HashSet::from([start]);
    let mut queue = VecDeque::from([start]);
    while let Some(occurrence_id) = queue.pop_front() {
        if occurrence_id == target {
            break;
        }
        for joint in &joints {
            let next = if joint.advanced.connector_a_occurrence_id == Some(occurrence_id) {
                joint.advanced.connector_b_occurrence_id?
            } else if joint.advanced.connector_b_occurrence_id == Some(occurrence_id) {
                joint.advanced.connector_a_occurrence_id?
            } else {
                continue;
            };
            if visited.insert(next) {
                previous.insert(next, (occurrence_id, joint.id));
                queue.push_back(next);
            }
        }
    }
    if !visited.contains(&target) {
        return None;
    }
    let mut path = Vec::new();
    let mut current = target;
    while current != start {
        let (prior, joint_id) = previous.get(&current).copied()?;
        path.push(joint_id);
        current = prior;
    }
    path.reverse();
    Some(path)
}

fn solution_occurrence_pose(
    solution: &AssemblySolutionDto,
    occurrence_id: OccurrenceId,
) -> Option<RigidPose> {
    solution
        .occurrence_poses
        .iter()
        .find(|pose| pose.occurrence_id == occurrence_id)
        .map(|pose| RigidPose {
            translation: pose.translation,
            rotation: pose.rotation,
        })
}

fn pose_residual(current: RigidPose, target: RigidPose) -> [f64; 6] {
    let translation = sub(current.translation, target.translation);
    let target_inverse = [
        -target.rotation[0],
        -target.rotation[1],
        -target.rotation[2],
        target.rotation[3],
    ];
    let mut error = normalize_quaternion(quaternion_mul(target_inverse, current.rotation));
    if error[3] < 0.0 {
        error = [-error[0], -error[1], -error[2], -error[3]];
    }
    let vector_length = length([error[0], error[1], error[2]]);
    let rotation = if vector_length <= 1.0e-12 {
        [0.0; 3]
    } else {
        let angle = 2.0 * vector_length.atan2(error[3]);
        scale([error[0], error[1], error[2]], angle / vector_length)
    };
    [
        translation[0],
        translation[1],
        translation[2],
        rotation[0],
        rotation[1],
        rotation[2],
    ]
}

fn clamp_coordinate(joint: &JointDefinitionDto, coordinate: JointCoordinate, value: f64) -> f64 {
    coordinate_limits(joint, coordinate)
        .map(|limits| value.clamp(limits.min, limits.max))
        .unwrap_or(value)
}

fn solve_linear_system(mut matrix: Vec<Vec<f64>>, mut rhs: Vec<f64>) -> Option<Vec<f64>> {
    let size = rhs.len();
    if matrix.len() != size || matrix.iter().any(|row| row.len() != size) {
        return None;
    }
    for pivot in 0..size {
        let best = (pivot..size)
            .max_by(|a, b| matrix[*a][pivot].abs().total_cmp(&matrix[*b][pivot].abs()))?;
        if matrix[best][pivot].abs() <= 1.0e-12 {
            return None;
        }
        matrix.swap(pivot, best);
        rhs.swap(pivot, best);
        let divisor = matrix[pivot][pivot];
        for column in pivot..size {
            matrix[pivot][column] /= divisor;
        }
        rhs[pivot] /= divisor;
        for row in 0..size {
            if row == pivot {
                continue;
            }
            let factor = matrix[row][pivot];
            if factor.abs() <= 1.0e-16 {
                continue;
            }
            for column in pivot..size {
                matrix[row][column] -= factor * matrix[pivot][column];
            }
            rhs[row] -= factor * rhs[pivot];
        }
    }
    Some(rhs)
}

fn validate_transform(transform: AssemblyTransformDto, label: &str) -> Result<(), String> {
    if !transform.translation.into_iter().all(f64::is_finite)
        || !transform.rotation.into_iter().all(f64::is_finite)
    {
        return Err(format!("{label} must contain finite values"));
    }
    if quaternion_dot(transform.rotation, transform.rotation) <= 1.0e-12 {
        return Err(format!("{label} rotation must be a non-zero quaternion"));
    }
    Ok(())
}

fn normalized_transform(transform: AssemblyTransformDto) -> AssemblyTransformDto {
    AssemblyTransformDto {
        translation: transform.translation,
        rotation: normalize_quaternion(transform.rotation),
    }
}

fn validate_occurrence_pair(
    structure: &ComponentStructureDto,
    occurrence_a: OccurrenceId,
    body_a: BodyId,
    occurrence_b: OccurrenceId,
    body_b: BodyId,
) -> Result<(), String> {
    if occurrence_a == occurrence_b {
        return Err("joint connectors must belong to different occurrences".to_string());
    }
    if !structure.occurrence_contains_body(occurrence_a, body_a) {
        return Err(format!(
            "occurrence {} does not contain connector body {}",
            occurrence_a.0, body_a.0
        ));
    }
    if !structure.occurrence_contains_body(occurrence_b, body_b) {
        return Err(format!(
            "occurrence {} does not contain connector body {}",
            occurrence_b.0, body_b.0
        ));
    }
    let parent_a = structure
        .occurrence(occurrence_a)
        .and_then(|occurrence| occurrence.parent_occurrence_id);
    let parent_b = structure
        .occurrence(occurrence_b)
        .and_then(|occurrence| occurrence.parent_occurrence_id);
    if parent_a != parent_b {
        return Err("joint connectors must be sibling occurrences in one subassembly".to_string());
    }
    Ok(())
}

fn unique_joint_name(
    existing: &[JointDefinitionDto],
    pending: &[JointDefinitionDto],
    base: &str,
) -> String {
    let taken = |name: &str| {
        existing.iter().any(|joint| joint.name == name)
            || pending.iter().any(|joint| joint.name == name)
    };
    if !taken(base) {
        return base.to_string();
    }
    for suffix in 2..u32::MAX {
        let candidate = format!("{base}:{suffix}");
        if !taken(&candidate) {
            return candidate;
        }
    }
    format!("{base}:copy")
}

pub fn connector_from_planar_face(
    body_id: BodyId,
    face: &FaceDto,
) -> Result<JointConnectorDto, String> {
    let plane = face
        .plane
        .ok_or_else(|| format!("face {} is not planar", face.id.0))?;
    let origin = face
        .signature
        .map(|signature| {
            [
                signature.centroid.x,
                signature.centroid.y,
                signature.centroid.z,
            ]
        })
        .unwrap_or(plane.origin);
    let connector = JointConnectorDto {
        body_id,
        face_id: face.id,
        face_key: face.key.clone(),
        edge_id: None,
        edge_key: None,
        kind: JointConnectorKindDto::PlanarFace,
        radius: None,
        source_surface_frame: None,
        frame: JointFrameDto {
            origin,
            primary_axis: plane.normal,
            secondary_axis: plane.u,
        },
    };
    validate_connector(&connector)?;
    Ok(connector)
}

pub fn connector_from_circular_edge(
    body_id: BodyId,
    edge: &EdgeDto,
) -> Result<JointConnectorDto, String> {
    let circle = edge
        .circle
        .filter(|circle| circle.closed)
        .ok_or_else(|| format!("edge {} is not a closed circle", edge.id.0))?;
    let connector = JointConnectorDto {
        body_id,
        face_id: FaceId(0),
        face_key: String::new(),
        edge_id: Some(edge.id),
        edge_key: Some(edge.key.clone()),
        kind: JointConnectorKindDto::CircularEdge,
        radius: Some(circle.radius),
        source_surface_frame: None,
        frame: JointFrameDto {
            origin: [circle.center.x, circle.center.y, circle.center.z],
            primary_axis: [circle.normal.x, circle.normal.y, circle.normal.z],
            secondary_axis: [circle.reference.x, circle.reference.y, circle.reference.z],
        },
    };
    validate_connector(&connector)?;
    Ok(connector)
}

fn validate_joint(joint: &JointDefinitionDto) -> Result<(), String> {
    if joint.id.0 == 0 {
        return Err("joint id must be non-zero".to_string());
    }
    if joint.name.trim().is_empty() {
        return Err(format!("joint {} requires a name", joint.id.0));
    }
    validate_connector(&joint.connector_a)?;
    validate_connector(&joint.connector_b)?;
    let distinct_occurrences = matches!(
        (joint.advanced.connector_a_occurrence_id, joint.advanced.connector_b_occurrence_id),
        (Some(a), Some(b)) if a != b
    );
    if joint.connector_a.body_id == joint.connector_b.body_id && !distinct_occurrences {
        return Err(format!(
            "joint '{}' must connect two different body occurrences",
            joint.name
        ));
    }
    if !joint.angle_offset_deg.is_finite()
        || !joint.linear_offset_mm.is_finite()
        || !joint.advanced.secondary_angle_offset_deg.is_finite()
        || !joint.advanced.tertiary_angle_offset_deg.is_finite()
        || !joint.advanced.secondary_linear_offset_mm.is_finite()
        || !joint.advanced.connector_a_twist_deg.is_finite()
        || !joint.advanced.connector_b_twist_deg.is_finite()
    {
        return Err(format!("joint '{}' has a non-finite offset", joint.name));
    }
    if !joint.advanced.screw_pitch_mm_per_revolution.is_finite()
        || joint.advanced.screw_pitch_mm_per_revolution <= 0.0
    {
        return Err(format!(
            "joint '{}' requires a positive screw pitch",
            joint.name
        ));
    }
    if joint.kind == JointKindDto::Rigid
        && (joint.angle_offset_deg != 0.0
            || joint.linear_offset_mm != 0.0
            || joint.advanced.secondary_angle_offset_deg != 0.0
            || joint.advanced.tertiary_angle_offset_deg != 0.0
            || joint.advanced.secondary_linear_offset_mm != 0.0)
    {
        return Err(format!(
            "rigid joint '{}' has no motion coordinates; position its connector frames instead",
            joint.name
        ));
    }
    if joint.kind == JointKindDto::Rigid
        && (joint.limits.is_some() || joint.angle_limits.is_some() || joint.linear_limits.is_some())
    {
        return Err(format!(
            "rigid joint '{}' cannot have motion limits",
            joint.name
        ));
    }
    if matches!(
        joint.kind,
        JointKindDto::Cylindrical
            | JointKindDto::Planar
            | JointKindDto::Ball
            | JointKindDto::PinSlot
            | JointKindDto::Universal
    ) && joint.limits.is_some()
    {
        return Err(format!(
            "multi-DOF joint '{}' requires axis-specific limits",
            joint.name
        ));
    }
    if joint.kind == JointKindDto::Revolute && joint.linear_limits.is_some() {
        return Err(format!(
            "revolute joint '{}' cannot have linear limits",
            joint.name
        ));
    }
    if joint.kind == JointKindDto::Slider && joint.angle_limits.is_some() {
        return Err(format!(
            "slider joint '{}' cannot have angle limits",
            joint.name
        ));
    }
    for limits in [
        joint.limits,
        joint.angle_limits,
        joint.linear_limits,
        joint.advanced.secondary_angle_limits,
        joint.advanced.tertiary_angle_limits,
        joint.advanced.secondary_linear_limits,
    ]
    .into_iter()
    .flatten()
    {
        if !limits.min.is_finite() || !limits.max.is_finite() || limits.min > limits.max {
            return Err(format!("joint '{}' has invalid motion limits", joint.name));
        }
    }
    Ok(())
}

fn validate_connector(connector: &JointConnectorDto) -> Result<(), String> {
    if connector.body_id.0 == 0 {
        return Err("joint connector requires a non-zero body id".to_string());
    }
    if connector.kind == JointConnectorKindDto::CircularEdge {
        let edge_id = connector
            .edge_id
            .ok_or_else(|| "circular joint connector requires an edge id".to_string())?;
        if edge_id.0 == 0 || connector.edge_key.as_deref().is_none_or(str::is_empty) {
            return Err("circular joint connector requires stable edge topology".to_string());
        }
        if connector
            .radius
            .is_none_or(|radius| !radius.is_finite() || radius <= 0.0)
        {
            return Err(format!(
                "circular edge {} requires a positive radius",
                edge_id.0
            ));
        }
    } else {
        if connector.face_id.0 == 0 {
            return Err("face joint connector requires a non-zero face id".to_string());
        }
        if connector.face_key.trim().is_empty() {
            return Err(format!(
                "joint connector face {} requires a stable topology key",
                connector.face_id.0
            ));
        }
        if connector
            .radius
            .is_some_and(|radius| !radius.is_finite() || radius <= 0.0)
        {
            return Err("joint connector radius must be positive".to_string());
        }
    }
    validate_connector_frame(connector.frame, "joint connector frame")?;
    if let Some(frame) = connector.source_surface_frame {
        validate_connector_frame(frame, "joint connector source surface frame")?;
    }
    Ok(())
}

fn validate_connector_frame(frame: JointFrameDto, label: &str) -> Result<(), String> {
    if !frame.origin.into_iter().all(f64::is_finite)
        || !frame.primary_axis.into_iter().all(f64::is_finite)
        || !frame.secondary_axis.into_iter().all(f64::is_finite)
    {
        return Err(format!("{label} must contain finite values"));
    }
    let primary_len = length(frame.primary_axis);
    let secondary_len = length(frame.secondary_axis);
    if primary_len <= 1e-9 || secondary_len <= 1e-9 {
        return Err(format!("{label} axes must be non-zero"));
    }
    let parallel =
        dot(frame.primary_axis, frame.secondary_axis).abs() / (primary_len * secondary_len);
    if parallel > 1.0 - 1e-6 {
        return Err(format!("{label} axes must not be parallel"));
    }
    Ok(())
}

fn canonical_connector_against_scene(
    connector: &JointConnectorDto,
    scene: &SolidSceneDto,
) -> Result<JointConnectorDto, String> {
    validate_connector(connector)?;
    let body = scene
        .bodies
        .iter()
        .find(|body| body.id == connector.body_id)
        .ok_or_else(|| format!("body {} no longer exists", connector.body_id.0))?;
    if connector.kind == JointConnectorKindDto::CircularEdge {
        let edge_id = connector.edge_id.expect("validated circular connector");
        let edge = body
            .edges
            .iter()
            .find(|edge| edge.id == edge_id)
            .ok_or_else(|| format!("edge {} no longer exists", edge_id.0))?;
        if connector.edge_key.as_deref() != Some(edge.key.as_str()) {
            return Err(format!(
                "edge {} topology changed; refusing to retarget joint connector",
                edge_id.0
            ));
        }
        return connector_from_circular_edge(body.id, edge);
    }
    let face = body
        .faces
        .iter()
        .find(|face| face.id == connector.face_id)
        .ok_or_else(|| format!("face {} no longer exists", connector.face_id.0))?;
    if face.key != connector.face_key {
        return Err(format!(
            "face {} topology changed; refusing to retarget joint connector",
            connector.face_id.0
        ));
    }
    match connector.kind {
        JointConnectorKindDto::PlanarFace => {
            let mut canonical = connector_from_planar_face(body.id, face)?;
            if let Some(source) = connector.source_surface_frame {
                let plane = face.plane.expect("validated planar face");
                let live = JointFrameDto {
                    origin: plane.origin,
                    primary_axis: plane.normal,
                    secondary_axis: plane.u,
                };
                // Preserve a picked attachment point relative to the exact
                // surface frame, including after a feature edit. Legacy
                // connectors without this frame retain centroid semantics.
                let delta =
                    RigidPose::from_frame(live).compose(RigidPose::from_frame(source).inverse());
                canonical.frame = JointFrameDto {
                    origin: add(
                        delta.translation,
                        rotate(delta.rotation, connector.frame.origin),
                    ),
                    primary_axis: rotate(delta.rotation, connector.frame.primary_axis),
                    secondary_axis: rotate(delta.rotation, connector.frame.secondary_axis),
                };
                canonical.source_surface_frame = Some(live);
                validate_connector(&canonical)?;
            }
            Ok(canonical)
        }
        JointConnectorKindDto::CylindricalFace | JointConnectorKindDto::VirtualCircularFace => {
            let cylinder = face
                .cylinder
                .ok_or_else(|| format!("face {} is no longer cylindrical", face.id.0))?;
            let axis = normalize([cylinder.axis.x, cylinder.axis.y, cylinder.axis.z]);
            let surface_origin = [cylinder.origin.x, cylinder.origin.y, cylinder.origin.z];
            let mut surface_reference = [
                cylinder.reference.x,
                cylinder.reference.y,
                cylinder.reference.z,
            ];
            surface_reference = sub(surface_reference, scale(axis, dot(surface_reference, axis)));
            if length(surface_reference) <= 1.0e-9 {
                return Err(format!(
                    "face {} has an invalid cylindrical reference direction",
                    face.id.0
                ));
            }
            let live_surface_frame = JointFrameDto {
                origin: surface_origin,
                primary_axis: axis,
                secondary_axis: normalize(surface_reference),
            };
            let frame = if let Some(source_surface_frame) = connector.source_surface_frame {
                // Map the originally picked connector through the exact rigid
                // change of the analytic cylinder frame. Re-projecting the old
                // point into the new cylinder loses axial translation and
                // arbitrary 3D rotation, which can tear an otherwise valid
                // multi-joint mechanism apart.
                let delta = RigidPose::from_frame(live_surface_frame)
                    .compose(RigidPose::from_frame(source_surface_frame).inverse());
                JointFrameDto {
                    origin: add(
                        delta.translation,
                        rotate(delta.rotation, connector.frame.origin),
                    ),
                    primary_axis: rotate(delta.rotation, connector.frame.primary_axis),
                    secondary_axis: rotate(delta.rotation, connector.frame.secondary_axis),
                }
            } else {
                // Legacy projects did not retain the analytic source frame.
                // Canonicalize once using the former behavior, then rebase the
                // returned connector onto today's live surface so all future
                // rigid edits are exact.
                let axial = dot(sub(connector.frame.origin, surface_origin), axis);
                let origin = add(surface_origin, scale(axis, axial));
                let mut secondary = sub(
                    connector.frame.secondary_axis,
                    scale(axis, dot(connector.frame.secondary_axis, axis)),
                );
                if length(secondary) <= 1.0e-9 {
                    secondary = live_surface_frame.secondary_axis;
                }
                let primary = if dot(connector.frame.primary_axis, axis) < 0.0 {
                    scale(axis, -1.0)
                } else {
                    axis
                };
                JointFrameDto {
                    origin,
                    primary_axis: primary,
                    secondary_axis: normalize(secondary),
                }
            };
            let canonical = JointConnectorDto {
                body_id: body.id,
                face_id: face.id,
                face_key: face.key.clone(),
                edge_id: None,
                edge_key: None,
                kind: connector.kind,
                radius: Some(cylinder.radius),
                source_surface_frame: Some(live_surface_frame),
                frame,
            };
            validate_connector(&canonical)?;
            Ok(canonical)
        }
        JointConnectorKindDto::CircularEdge => unreachable!("handled before face lookup"),
    }
}

fn length(value: [f64; 3]) -> f64 {
    dot(value, value).sqrt()
}

fn dot(a: [f64; 3], b: [f64; 3]) -> f64 {
    a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
}

fn add(a: [f64; 3], b: [f64; 3]) -> [f64; 3] {
    [a[0] + b[0], a[1] + b[1], a[2] + b[2]]
}

fn sub(a: [f64; 3], b: [f64; 3]) -> [f64; 3] {
    [a[0] - b[0], a[1] - b[1], a[2] - b[2]]
}

fn scale(value: [f64; 3], factor: f64) -> [f64; 3] {
    [value[0] * factor, value[1] * factor, value[2] * factor]
}

fn normalize(value: [f64; 3]) -> [f64; 3] {
    let magnitude = length(value);
    if magnitude <= 1.0e-12 {
        [0.0; 3]
    } else {
        scale(value, magnitude.recip())
    }
}

fn cross(a: [f64; 3], b: [f64; 3]) -> [f64; 3] {
    [
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    ]
}

fn quaternion_mul(a: [f64; 4], b: [f64; 4]) -> [f64; 4] {
    [
        a[3] * b[0] + a[0] * b[3] + a[1] * b[2] - a[2] * b[1],
        a[3] * b[1] - a[0] * b[2] + a[1] * b[3] + a[2] * b[0],
        a[3] * b[2] + a[0] * b[1] - a[1] * b[0] + a[2] * b[3],
        a[3] * b[3] - a[0] * b[0] - a[1] * b[1] - a[2] * b[2],
    ]
}

fn quaternion_dot(a: [f64; 4], b: [f64; 4]) -> f64 {
    a[0] * b[0] + a[1] * b[1] + a[2] * b[2] + a[3] * b[3]
}

fn normalize_quaternion(value: [f64; 4]) -> [f64; 4] {
    let magnitude = quaternion_dot(value, value).sqrt();
    if magnitude <= 1.0e-12 {
        [0.0, 0.0, 0.0, 1.0]
    } else {
        [
            value[0] / magnitude,
            value[1] / magnitude,
            value[2] / magnitude,
            value[3] / magnitude,
        ]
    }
}

fn rotate(rotation: [f64; 4], point: [f64; 3]) -> [f64; 3] {
    let q = [point[0], point[1], point[2], 0.0];
    let inverse = [-rotation[0], -rotation[1], -rotation[2], rotation[3]];
    let result = quaternion_mul(quaternion_mul(rotation, q), inverse);
    [result[0], result[1], result[2]]
}

fn quaternion_from_basis(x: [f64; 3], y: [f64; 3], z: [f64; 3]) -> [f64; 4] {
    // Matrix columns are the connector's orthonormal x, y, z axes.
    let m00 = x[0];
    let m01 = y[0];
    let m02 = z[0];
    let m10 = x[1];
    let m11 = y[1];
    let m12 = z[1];
    let m20 = x[2];
    let m21 = y[2];
    let m22 = z[2];
    let trace = m00 + m11 + m22;
    let quaternion = if trace > 0.0 {
        let s = (trace + 1.0).sqrt() * 2.0;
        [(m21 - m12) / s, (m02 - m20) / s, (m10 - m01) / s, 0.25 * s]
    } else if m00 > m11 && m00 > m22 {
        let s = (1.0 + m00 - m11 - m22).sqrt() * 2.0;
        [0.25 * s, (m01 + m10) / s, (m02 + m20) / s, (m21 - m12) / s]
    } else if m11 > m22 {
        let s = (1.0 + m11 - m00 - m22).sqrt() * 2.0;
        [(m01 + m10) / s, 0.25 * s, (m12 + m21) / s, (m02 - m20) / s]
    } else {
        let s = (1.0 + m22 - m00 - m11).sqrt() * 2.0;
        [(m02 + m20) / s, (m12 + m21) / s, 0.25 * s, (m10 - m01) / s]
    };
    normalize_quaternion(quaternion)
}

